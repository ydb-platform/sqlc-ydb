// Package rust renders resolved YQL queries for the official YDB Rust SDK.
package rust

import (
	"fmt"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/ydb-platform/sqlc-ydb/internal/model"
)

type Options struct {
	Runtime string
}

func Generate(in *model.AnalysisResult, opts Options) ([]model.File, error) {
	if in == nil {
		return nil, fmt.Errorf("rust generator: nil analysis result")
	}
	if len(in.Diagnostics) != 0 {
		return nil, fmt.Errorf("rust generator: analysis has diagnostics: %s", in.Diagnostics[0])
	}
	if opts.Runtime == "" {
		opts.Runtime = "ydb"
	}
	if opts.Runtime != "ydb" {
		return nil, fmt.Errorf("rust generator: unsupported runtime %q", opts.Runtime)
	}
	if err := validate(in); err != nil {
		return nil, err
	}
	return []model.File{
		{Name: "models.rs", Content: []byte(renderModels(in))},
		{Name: "queries.rs", Content: []byte(renderQueries(in))},
		{Name: "lib.rs", Content: []byte("// Code generated by sqlc-ydb. DO NOT EDIT.\npub mod models;\npub mod queries;\n")},
	}, nil
}

func validate(in *model.AnalysisResult) error {
	queries, constants, rows := map[string]string{}, map[string]string{}, map[string]string{}
	for _, q := range in.Queries {
		if !utf8.ValidString(q.SQL) {
			return fmt.Errorf("rust generator: query %q: SQL is not valid UTF-8", q.Name)
		}
		fn := snakeName(q.Name)
		constant := screamingName(q.Name)
		row := pascalName(q.Name) + "Row"
		if !rustIdent(fn) || rustKeywords[fn] {
			return fmt.Errorf("rust generator: query %q has invalid generated Rust name %q", q.Name, fn)
		}
		if fn == "new" {
			return fmt.Errorf("rust generator: query %q conflicts with the generated constructor new; rename the query", q.Name)
		}
		if previous, ok := queries[fn]; ok {
			return fmt.Errorf("rust generator: query name collision at %q (%q and %q)", fn, previous, q.Name)
		}
		queries[fn] = q.Name
		if previous, ok := constants[constant]; ok {
			return fmt.Errorf("rust generator: query constant collision at %q (%q and %q)", constant, previous, q.Name)
		}
		constants[constant] = q.Name
		if previous, ok := rows[row]; ok {
			return fmt.Errorf("rust generator: row type name collision at %q (%q and %q)", row, previous, q.Name)
		}
		rows[row] = q.Name
		switch q.Command {
		case model.One, model.Many:
			if len(q.ResultSets) != 1 || len(q.ResultSets[0].Columns) == 0 {
				return fmt.Errorf("rust generator: query %q: expected one non-empty result set for %s", q.Name, q.Command)
			}
		case model.Exec:
		case model.ExecRows:
			return fmt.Errorf("rust generator: query %q: :execrows is unsupported because YDB QueryClient does not expose an affected-row count", q.Name)
		default:
			return fmt.Errorf("rust generator: query %q: unsupported command %q", q.Name, q.Command)
		}
		paramNames := map[string]string{}
		for _, p := range q.Parameters {
			name := snakeName(p.Name)
			if !rustIdent(name) || rustKeywords[name] || name == "self" {
				return fmt.Errorf("rust generator: query %q parameter %q has invalid generated Rust name %q", q.Name, p.Name, name)
			}
			if previous, ok := paramNames[name]; ok {
				return fmt.Errorf("rust generator: query %q parameter name collision at %q (%q and %q)", q.Name, name, previous, p.Name)
			}
			paramNames[name] = p.Name
			if _, err := rustType(p.Type); err != nil {
				return fmt.Errorf("rust generator: query %q parameter %q: %w", q.Name, p.Name, err)
			}
		}
		for _, rs := range q.ResultSets {
			columnNames := map[string]string{}
			for _, c := range rs.Columns {
				name := snakeName(c.Name)
				if !rustIdent(name) || rustKeywords[name] {
					return fmt.Errorf("rust generator: query %q column %q has invalid generated Rust name %q", q.Name, c.Name, name)
				}
				if previous, ok := columnNames[name]; ok {
					return fmt.Errorf("rust generator: query %q column name collision at %q (%q and %q)", q.Name, name, previous, c.Name)
				}
				columnNames[name] = c.Name
				if _, err := rustType(c.Type); err != nil {
					return fmt.Errorf("rust generator: query %q column %q: %w", q.Name, c.Name, err)
				}
			}
		}
	}
	return nil
}

func renderModels(in *model.AnalysisResult) string {
	var b strings.Builder
	b.WriteString("// Code generated by sqlc-ydb. DO NOT EDIT.\n\n")
	for _, q := range in.Queries {
		if q.Command != model.One && q.Command != model.Many {
			continue
		}
		fmt.Fprintf(&b, "#[derive(Debug, Clone, PartialEq)]\npub struct %sRow {\n", pascalName(q.Name))
		for _, c := range q.ResultSets[0].Columns {
			t, _ := rustType(c.Type)
			fmt.Fprintf(&b, "    pub %s: %s,\n", snakeName(c.Name), t)
		}
		b.WriteString("}\n\n")
	}
	return strings.TrimSuffix(b.String(), "\n")
}

func renderQueries(in *model.AnalysisResult) string {
	var b strings.Builder
	b.WriteString("// Code generated by sqlc-ydb. DO NOT EDIT.\n\nuse super::models::*;\n\n")
	for _, q := range in.Queries {
		fmt.Fprintf(&b, "pub const %s: &str = %s;\n\n", screamingName(q.Name), rustString(q.SQL))
	}
	if hasParameterKind(in, "json") {
		b.WriteString("#[derive(Default)]\nstruct JsonParam(String);\n\nimpl From<JsonParam> for ydb::Value {\n    fn from(value: JsonParam) -> Self {\n        ydb::Value::Json(value.0)\n    }\n}\n\n")
	}
	if hasParameterKind(in, "jsondocument") {
		b.WriteString("#[derive(Default)]\nstruct JsonDocumentParam(String);\n\nimpl From<JsonDocumentParam> for ydb::Value {\n    fn from(value: JsonDocumentParam) -> Self {\n        ydb::Value::JsonDocument(value.0)\n    }\n}\n\n")
	}
	for _, kind := range temporalKinds {
		if !hasParameterKind(in, kind) {
			continue
		}
		variant := temporalVariant(kind)
		fmt.Fprintf(&b, "struct %sParam(std::time::SystemTime);\n\nimpl Default for %sParam {\n    fn default() -> Self {\n        Self(std::time::SystemTime::UNIX_EPOCH)\n    }\n}\n\nimpl From<%sParam> for ydb::Value {\n    fn from(value: %sParam) -> Self {\n        ydb::Value::%s(value.0)\n    }\n}\n\n", variant, variant, variant, variant, variant)
	}
	b.WriteString("pub struct Queries<'a> {\n    client: &'a mut ydb::QueryClient,\n}\n\nimpl<'a> Queries<'a> {\n    pub fn new(client: &'a mut ydb::QueryClient) -> Self {\n        Self { client }\n    }\n\n")
	for _, q := range in.Queries {
		renderMethod(&b, q)
	}
	b.WriteString("}\n")
	return b.String()
}

func renderMethod(b *strings.Builder, q model.AnalyzedQuery) {
	fmt.Fprintf(b, "    pub async fn %s(&mut self", snakeName(q.Name))
	for _, p := range q.Parameters {
		t, _ := rustType(p.Type)
		fmt.Fprintf(b, ", %s: %s", snakeName(p.Name), t)
	}
	ret := "()"
	if q.Command == model.One {
		ret = pascalName(q.Name) + "Row"
	} else if q.Command == model.Many {
		ret = "Vec<" + pascalName(q.Name) + "Row>"
	}
	fmt.Fprintf(b, ") -> ydb::YdbResult<%s> {\n", ret)
	method := "exec"
	if q.Command == model.One || q.Command == model.Many {
		method = "query_result_set"
	}
	fmt.Fprintf(b, "        let call = self.client.%s(%s)", method, screamingName(q.Name))
	for _, p := range q.Parameters {
		fmt.Fprintf(b, "\n            .param(%q, %s)", "$"+p.Name, bindExpression(p))
	}
	b.WriteString(";\n")
	switch q.Command {
	case model.Exec:
		b.WriteString("        call.await\n")
	case model.One:
		b.WriteString("        let result_set = call.await?;\n        let mut row = result_set.rows().next().ok_or(ydb::YdbError::NoRows)?;\n        Ok(")
		renderRow(b, q, "")
		b.WriteString(")\n")
	case model.Many:
		b.WriteString("        let result_set = call.await?;\n        let mut rows = Vec::new();\n        for mut row in result_set.rows() {\n            rows.push(")
		renderRow(b, q, "    ")
		b.WriteString(");\n        }\n        Ok(rows)\n")
	}
	b.WriteString("    }\n\n")
}

func renderRow(b *strings.Builder, q model.AnalyzedQuery, indent string) {
	fmt.Fprintf(b, "%sRow {\n", pascalName(q.Name))
	for index, c := range q.ResultSets[0].Columns {
		fmt.Fprintf(b, "        %s    %s: row.remove_field(%d)?.try_into()?,\n", indent, snakeName(c.Name), index)
	}
	fmt.Fprintf(b, "        %s}", indent)
}

func bindExpression(p model.Parameter) string {
	name := snakeName(p.Name)
	t := p.Type
	optional := t.IsOptional() && t.Elem != nil
	if optional {
		t = *t.Elem
	}
	switch strings.ToLower(t.Kind) {
	case "json":
		if optional {
			return name + ".map(JsonParam)"
		}
		return "JsonParam(" + name + ")"
	case "jsondocument":
		if optional {
			return name + ".map(JsonDocumentParam)"
		}
		return "JsonDocumentParam(" + name + ")"
	case "string", "yson":
		if optional {
			return name + ".map(ydb::Bytes::from)"
		}
		return "ydb::Bytes::from(" + name + ")"
	default:
		if variant := temporalVariant(t.Kind); variant != "" {
			if optional {
				return name + ".map(" + variant + "Param)"
			}
			return variant + "Param(" + name + ")"
		}
		return name
	}
}

var temporalKinds = []string{"date", "datetime", "timestamp", "date32", "datetime64", "timestamp64"}

func temporalVariant(kind string) string {
	switch strings.ToLower(kind) {
	case "date":
		return "Date"
	case "datetime":
		return "DateTime"
	case "timestamp":
		return "Timestamp"
	case "date32":
		return "Date32"
	case "datetime64":
		return "Datetime64"
	case "timestamp64":
		return "Timestamp64"
	default:
		return ""
	}
}

func hasParameterKind(in *model.AnalysisResult, kind string) bool {
	for _, q := range in.Queries {
		for _, p := range q.Parameters {
			t := p.Type.UnwrapOptional()
			if strings.EqualFold(t.Kind, kind) {
				return true
			}
		}
	}
	return false
}

func rustType(t model.Type) (string, error) {
	if t.IsOptional() {
		if t.Elem == nil {
			return "", fmt.Errorf("Optional lacks element")
		}
		inner, err := rustType(*t.Elem)
		return "Option<" + inner + ">", err
	}
	switch strings.ToLower(t.Kind) {
	case "bool":
		return "bool", nil
	case "int8":
		return "i8", nil
	case "int16":
		return "i16", nil
	case "int32":
		return "i32", nil
	case "int64":
		return "i64", nil
	case "uint8":
		return "u8", nil
	case "uint16":
		return "u16", nil
	case "uint32":
		return "u32", nil
	case "uint64":
		return "u64", nil
	case "float":
		return "f32", nil
	case "double":
		return "f64", nil
	case "utf8", "json", "jsondocument":
		return "String", nil
	case "string", "yson":
		return "ydb::Bytes", nil
	case "timestamp", "timestamp64", "date", "date32", "datetime", "datetime64":
		return "std::time::SystemTime", nil
	default:
		return "", fmt.Errorf("unsupported YQL type %q", t.Kind)
	}
}

func rustString(s string) string {
	parts := make([]string, 0, 3)
	start := 0
	for i, r := range s {
		if r != '\r' && r != 0 && (r >= 0x20 || r == '\n' || r == '\t') && r != 0x7f {
			continue
		}
		if start < i {
			parts = append(parts, rawString(s[start:i]))
		}
		width := utf8.RuneLen(r)
		if width < 1 {
			width = 1
		}
		parts = append(parts, fmt.Sprintf("\"\\x%02x\"", []byte(s[i : i+width])[0]))
		start = i + width
	}
	if start < len(s) || len(parts) == 0 {
		parts = append(parts, rawString(s[start:]))
	}
	if len(parts) == 1 {
		return parts[0]
	}
	return "concat!(" + strings.Join(parts, ", ") + ")"
}

func rawString(s string) string {
	for hashes := 0; ; hashes++ {
		delim := strings.Repeat("#", hashes)
		if !strings.Contains(s, "\""+delim) {
			return "r" + delim + "\"" + s + "\"" + delim
		}
	}
}

func words(s string) []string {
	var out []string
	start := -1
	runes := []rune(s)
	flush := func(end int) {
		if start >= 0 && start < end {
			out = append(out, strings.ToLower(string(runes[start:end])))
		}
		start = -1
	}
	for i, r := range runes {
		if !(r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r)) {
			flush(i)
			continue
		}
		if r == '_' {
			flush(i)
			continue
		}
		if start < 0 {
			start = i
			continue
		}
		prev := runes[i-1]
		if unicode.IsUpper(r) && (unicode.IsLower(prev) || unicode.IsDigit(prev)) || unicode.IsUpper(r) && unicode.IsUpper(prev) && i+1 < len(runes) && unicode.IsLower(runes[i+1]) {
			flush(i)
			start = i
		}
	}
	flush(len(runes))
	return out
}

func snakeName(s string) string { return strings.Join(words(s), "_") }

func screamingName(s string) string { return strings.ToUpper(snakeName(s)) }

func pascalName(s string) string {
	parts := words(s)
	for i := range parts {
		r, size := utf8.DecodeRuneInString(parts[i])
		parts[i] = string(unicode.ToUpper(r)) + parts[i][size:]
	}
	return strings.Join(parts, "")
}

func rustIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if r > unicode.MaxASCII || !(r == '_' || unicode.IsLetter(r) || i > 0 && unicode.IsDigit(r)) {
			return false
		}
	}
	return true
}

var rustKeywords = func() map[string]bool {
	keywords := strings.Fields("as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try union")
	out := make(map[string]bool, len(keywords))
	for _, keyword := range keywords {
		out[keyword] = true
	}
	return out
}()
