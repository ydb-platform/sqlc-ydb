package codegen

import (
	"bytes"
	"context"
	"strings"

	"github.com/sqlc-dev/sqlc-engine-ydb/internal/codegen/pb"
)

func generateYdbPythonSDK(ctx context.Context, req *pb.GenerateRequest) (*pb.GenerateResponse, error) {
	opts, err := parseOptions(req.GetPluginOptions())
	if err != nil {
		return nil, err
	}
	pkg := opts.Package
	if pkg == "" {
		pkg = "db"
	}

	var files []*pb.File

	models, err := pysdkGenModels(req.GetCatalog(), req.GetQueries(), pkg)
	if err != nil {
		return nil, err
	}
	files = append(files, &pb.File{Name: "models.py", Contents: models})

	initPy := []byte("# Code generated by sqlc. DO NOT EDIT.\n\n")
	files = append(files, &pb.File{Name: "__init__.py", Contents: initPy})

	byFilename := make(map[string][]*pb.Query)
	for _, q := range req.GetQueries() {
		fn := q.GetFilename()
		if fn == "" {
			fn = "query.sql"
		}
		if idx := strings.LastIndex(fn, "/"); idx >= 0 {
			fn = fn[idx+1:]
		}
		byFilename[fn] = append(byFilename[fn], q)
	}
	for fname, qs := range byFilename {
		outName := strings.TrimSuffix(fname, ".sql") + ".py"
		if outName == fname {
			outName = "query.py"
		}
		content, err := pysdkGenQueryFile(req.GetCatalog(), pkg, fname, qs)
		if err != nil {
			return nil, err
		}
		files = append(files, &pb.File{Name: outName, Contents: content})
	}

	return &pb.GenerateResponse{Files: files}, nil
}

func toPythonClass(s string) string {
	if s == "" {
		return "T"
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func pysdkQueryMethodName(name string) string {
	return toSnake(name)
}

func pysdkGenModels(cat *pb.Catalog, queries []*pb.Query, pkg string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("# Code generated by sqlc. DO NOT EDIT.\n")
	buf.WriteString("import dataclasses\n")
	buf.WriteString("from typing import Optional\n\n")

	for _, schema := range cat.GetSchemas() {
		for _, tbl := range schema.GetTables() {
			name := tbl.GetRel().GetName()
			if name == "" {
				continue
			}
			className := toPythonClass(name)
			buf.WriteString("@dataclasses.dataclass\n")
			buf.WriteString("class " + className + ":\n")
			for _, col := range tbl.GetColumns() {
				yt := ydbTypeName(col)
				pyType := pythonType(yt, col.GetNotNull())
				fieldName := toSnake(col.GetName())
				buf.WriteString("    " + fieldName + ": " + pyType + "\n")
			}
			buf.WriteString("\n")
		}
	}

	hasCatalogTables := false
	for _, s := range cat.GetSchemas() {
		if len(s.GetTables()) > 0 {
			hasCatalogTables = true
			break
		}
	}
	if !hasCatalogTables {
		for _, q := range queries {
			cols := q.GetColumns()
			if len(cols) == 0 {
				continue
			}
			cmd := strings.ToLower(q.GetCmd())
			if cmd != ":one" && cmd != ":many" {
				continue
			}
			name := toPythonClass(q.GetName() + "Row")
			buf.WriteString("@dataclasses.dataclass\n")
			buf.WriteString("class " + name + ":\n")
			for _, col := range cols {
				yt := ydbTypeName(col)
				pyType := pythonType(yt, col.GetNotNull())
				fieldName := toSnake(col.GetName())
				buf.WriteString("    " + fieldName + ": " + pyType + "\n")
			}
			buf.WriteString("\n")
		}
	}
	return buf.Bytes(), nil
}

func pysdkGenQueryFile(cat *pb.Catalog, pkg, sourceName string, queries []*pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("# Code generated by sqlc. DO NOT EDIT.\n")
	buf.WriteString("# source: " + sourceName + "\n")
	buf.WriteString("from typing import Iterator, Optional\n\n")
	buf.WriteString("import ydb\n\n")
	buf.WriteString("from " + pkg + " import models\n\n")

	for i, q := range queries {
		block, err := pysdkGenQuery(cat, pkg, q)
		if err != nil {
			return nil, err
		}
		buf.Write(block)
		if i < len(queries)-1 {
			buf.WriteString("\n")
		}
	}

	buf.WriteString("\n\nclass Querier:\n")
	buf.WriteString("    def __init__(self, pool: ydb.QuerySessionPool):\n")
	buf.WriteString("        self._pool = pool\n\n")

	for _, q := range queries {
		meth, err := pysdkGenMethod(cat, pkg, q)
		if err != nil {
			return nil, err
		}
		buf.Write(meth)
	}

	return buf.Bytes(), nil
}

func pysdkToConstName(name string) string {
	return strings.ToUpper(toSnake(name))
}

func pysdkGenQuery(cat *pb.Catalog, pkg string, q *pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	name := q.GetName()
	text := q.GetText()
	constName := pysdkToConstName(name)
	buf.WriteString(constName + " = \"\"\"\n" + text + "\n\"\"\"\n\n")
	return buf.Bytes(), nil
}

func pysdkParamsDict(params []*pb.Parameter) string {
	var parts []string
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		paramName := col.GetName()
		argName := toSnake(paramName)
		parts = append(parts, "\"$"+paramName+"\": "+argName)
	}
	return strings.Join(parts, ", ")
}

func pysdkGenMethod(cat *pb.Catalog, pkg string, q *pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	name := q.GetName()
	cmd := strings.ToLower(q.GetCmd())
	methodName := pysdkQueryMethodName(name)
	constName := pysdkToConstName(name)
	params := q.GetParams()
	cols := q.GetColumns()

	paramNames := make([]string, 0, len(params))
	for _, p := range params {
		if col := p.GetColumn(); col != nil {
			paramNames = append(paramNames, col.GetName())
		}
	}

	rowClassName := ""
	if len(cols) > 0 {
		for _, c := range cols {
			if t := c.GetTable(); t != nil && t.GetName() != "" && catalogHasTable(cat, t.GetName()) {
				rowClassName = toPythonClass(t.GetName())
				break
			}
		}
		if rowClassName == "" {
			rowClassName = toPythonClass(name + "Row")
		}
	}
	if (cmd == ":one" || cmd == ":many") && rowClassName == "" {
		rowClassName = toPythonClass(name + "Row")
	}

	paramsArg := "parameters={}"
	if len(paramNames) > 0 {
		paramsArg = "parameters={" + pysdkParamsDict(params) + "}"
	}

	switch cmd {
	case ":one":
		buf.WriteString("    def " + methodName + "(self")
		for _, p := range params {
			if col := p.GetColumn(); col != nil {
				yt := ydbTypeName(col)
				pyType := pythonType(yt, col.GetNotNull())
				buf.WriteString(", *, " + toSnake(col.GetName()) + ": " + pyType)
			}
		}
		buf.WriteString(") -> Optional[models." + rowClassName + "]:\n")
		buf.WriteString("        result_sets = self._pool.execute_with_retries(" + constName + ", " + paramsArg + ")\n")
		buf.WriteString("        if not result_sets or not result_sets[0].rows:\n")
		buf.WriteString("            return None\n")
		buf.WriteString("        row = result_sets[0].rows[0]\n")
		buf.WriteString("        return models." + rowClassName + "(\n")
		for i, c := range cols {
			field := toSnake(c.GetName())
			buf.WriteString("            " + field + "=row." + field)
			if i < len(cols)-1 {
				buf.WriteString(",")
			}
			buf.WriteString("\n")
		}
		buf.WriteString("        )\n\n")

	case ":many":
		buf.WriteString("    def " + methodName + "(self")
		for _, p := range params {
			if col := p.GetColumn(); col != nil {
				yt := ydbTypeName(col)
				pyType := pythonType(yt, col.GetNotNull())
				buf.WriteString(", *, " + toSnake(col.GetName()) + ": " + pyType)
			}
		}
		buf.WriteString(") -> Iterator[models." + rowClassName + "]:\n")
		buf.WriteString("        result_sets = self._pool.execute_with_retries(" + constName + ", " + paramsArg + ")\n")
		buf.WriteString("        for row in result_sets[0].rows:\n")
		buf.WriteString("            yield models." + rowClassName + "(\n")
		for i, c := range cols {
			field := toSnake(c.GetName())
			buf.WriteString("                " + field + "=row." + field)
			if i < len(cols)-1 {
				buf.WriteString(",")
			}
			buf.WriteString("\n")
		}
		buf.WriteString("            )\n\n")

	default:
		buf.WriteString("    def " + methodName + "(self")
		for _, p := range params {
			if col := p.GetColumn(); col != nil {
				yt := ydbTypeName(col)
				pyType := pythonType(yt, col.GetNotNull())
				buf.WriteString(", *, " + toSnake(col.GetName()) + ": " + pyType)
			}
		}
		buf.WriteString(") -> None:\n")
		buf.WriteString("        self._pool.execute_with_retries(" + constName + ", " + paramsArg + ")\n\n")
	}
	return buf.Bytes(), nil
}
