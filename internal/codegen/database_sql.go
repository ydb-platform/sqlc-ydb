package codegen

import (
	"bytes"
	"context"
	"strings"
	"text/template"

	"github.com/sqlc-dev/sqlc-engine-ydb/internal/codegen/pb"
)

var _ Generator = generatorDatabaseSQL{}

type generatorDatabaseSQL struct{}

func (g generatorDatabaseSQL) Name() string {
	return "database/sql"
}

func (g generatorDatabaseSQL) Generate(ctx context.Context, req *pb.GenerateRequest) (*pb.GenerateResponse, error) {
	opts, err := parseOptions(req.GetPluginOptions())
	if err != nil {
		return nil, err
	}
	pkg := opts.Package
	if pkg == "" {
		pkg = "db"
	}
	outDir := "."
	if s := req.GetSettings(); s != nil && s.GetCodegen() != nil {
		outDir = s.GetCodegen().GetOut()
	}
	if outDir == "" {
		outDir = "."
	}

	var files []*pb.File

	models, err := g.models(req.GetCatalog(), req.GetQueries(), pkg)
	if err != nil {
		return nil, err
	}
	files = append(files, &pb.File{Name: "models.go", Contents: models})

	db, err := g.db(pkg)
	if err != nil {
		return nil, err
	}
	files = append(files, &pb.File{Name: "db.go", Contents: db})

	byFilename := make(map[string][]*pb.Query)
	for _, q := range req.GetQueries() {
		fn := q.GetFilename()
		if fn == "" {
			fn = "query.sql"
		}
		if idx := strings.LastIndex(fn, "/"); idx >= 0 {
			fn = fn[idx+1:]
		}
		byFilename[fn] = append(byFilename[fn], q)
	}
	for fname, qs := range byFilename {
		outName := strings.TrimSuffix(fname, ".sql") + ".sql.go"
		if outName == fname {
			outName = "query.sql.go"
		}
		content, err := g.queries(req.GetCatalog(), pkg, fname, qs)
		if err != nil {
			return nil, err
		}
		files = append(files, &pb.File{Name: outName, Contents: content})
	}

	return &pb.GenerateResponse{Files: files}, nil
}

func (g generatorDatabaseSQL) models(cat *pb.Catalog, queries []*pb.Query, pkg string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sqlc. DO NOT EDIT.\n")
	buf.WriteString("package " + pkg + "\n\n")

	for _, schema := range cat.GetSchemas() {
		for _, tbl := range schema.GetTables() {
			name := tbl.GetRel().GetName()
			if name == "" {
				continue
			}
			structName := tableNameToGoStruct(name)
			buf.WriteString("type " + structName + " struct {\n")
			for _, col := range tbl.GetColumns() {
				yt := ydbTypeName(col)
				goType := goTypeForDB(yt, col.GetNotNull())
				fname := toGoField(col.GetName())
				buf.WriteString("\t" + fname + " " + goType + " `json:\"" + col.GetName() + "\"`\n")
			}
			buf.WriteString("}\n\n")
		}
	}

	hasCatalogTables := false
	for _, s := range cat.GetSchemas() {
		if len(s.GetTables()) > 0 {
			hasCatalogTables = true
			break
		}
	}
	if !hasCatalogTables {
		for _, q := range queries {
			cols := q.GetColumns()
			if len(cols) == 0 {
				continue
			}
			cmd := strings.ToLower(q.GetCmd())
			if cmd != ":one" && cmd != ":many" {
				continue
			}
			name := q.GetName() + "Row"
			buf.WriteString("type " + name + " struct {\n")
			for _, col := range cols {
				yt := ydbTypeName(col)
				goType := goTypeForDB(yt, col.GetNotNull())
				fname := toGoField(col.GetName())
				buf.WriteString("\t" + fname + " " + goType + " `json:\"" + col.GetName() + "\"`\n")
			}
			buf.WriteString("}\n\n")
		}
	}
	return buf.Bytes(), nil
}

func (g generatorDatabaseSQL) db(pkg string) ([]byte, error) {
	const dbsqlDBTemplate = `// Code generated by sqlc. DO NOT EDIT.
package {{.Package}}

import (
	"context"
	"database/sql"
)

type DBTX interface {
	ExecContext(context.Context, string, ...interface{}) (sql.Result, error)
	QueryContext(context.Context, string, ...interface{}) (*sql.Rows, error)
	QueryRowContext(context.Context, string, ...interface{}) *sql.Row
}

func New(db DBTX) *Queries {
	return &Queries{db: db}
}

type Queries struct {
	db DBTX
}
`
	t := template.Must(template.New("db").Parse(dbsqlDBTemplate))
	var buf bytes.Buffer
	if err := t.Execute(&buf, map[string]string{"Package": pkg}); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func (g generatorDatabaseSQL) queries(cat *pb.Catalog, pkg, sourceName string, queries []*pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sqlc. DO NOT EDIT.\n// source: " + sourceName + "\n\n")
	buf.WriteString("package " + pkg + "\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"database/sql\"\n\n")
	buf.WriteString("\t_ \"github.com/ydb-platform/ydb-go-sdk/v3\"\n")
	buf.WriteString("\t\"github.com/ydb-platform/ydb-go-sdk/v3/pkg/xerrors\"\n")
	buf.WriteString("\t\"github.com/ydb-platform/ydb-go-sdk/v3/retry\"\n")
	buf.WriteString(")\n\n")

	for i, q := range queries {
		block, err := g.query(cat, pkg, q)
		if err != nil {
			return nil, err
		}
		buf.Write(block)
		if i < len(queries)-1 {
			buf.WriteString("\n")
		}
	}
	return buf.Bytes(), nil
}

func (g generatorDatabaseSQL) query(cat *pb.Catalog, pkg string, q *pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	name := q.GetName()
	cmd := strings.ToLower(q.GetCmd())
	text := q.GetText()

	constName := toGoConst(name)
	buf.WriteString("const " + constName + " = `" + text + "`\n\n")

	switch cmd {
	case ":one":
		buf.WriteString(g.one(cat, name, constName, q))
	case ":many":
		buf.WriteString(g.many(cat, name, constName, q))
	default:
		buf.WriteString(g.exec(name, constName, q))
	}
	return buf.Bytes(), nil
}

// goParamList returns "id uint64, name string, bio *string" for method signature.
func (g generatorDatabaseSQL) goParamList(params []*pb.Parameter) string {
	var parts []string
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		yt := ydbTypeName(col)
		goType := goTypeForDB(yt, col.GetNotNull())
		parts = append(parts, toGoParamName(col.GetName())+" "+goType)
	}
	return strings.Join(parts, ", ")
}

// writeFuncSignature writes a multi-line signature when params exist: ctx on first line, each param on its own line, then return type.
func (g generatorDatabaseSQL) writeFuncSignature(b *bytes.Buffer, name string, params []*pb.Parameter, returnType string) {
	if len(params) == 0 {
		b.WriteString("func (q *Queries) " + name + "(ctx context.Context) " + returnType + " {\n")
		return
	}
	b.WriteString("func (q *Queries) " + name + "(ctx context.Context,\n")
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		yt := ydbTypeName(col)
		goType := goTypeForDB(yt, col.GetNotNull())
		b.WriteString("\t" + toGoParamName(col.GetName()) + " " + goType + ",\n")
	}
	b.WriteString(") " + returnType + " {\n")
}

func (g generatorDatabaseSQL) namedArgsList(params []*pb.Parameter) string {
	if len(params) == 0 {
		return ""
	}
	var parts []string
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		paramName := col.GetName()
		argName := toGoParamName(paramName)
		parts = append(parts, "sql.Named(\""+paramName+"\", "+argName+")")
	}
	if len(parts) == 0 {
		return ""
	}
	return ",\n\t\t\t" + strings.Join(parts, ",\n\t\t\t") + ",\n\t\t"
}

func (g generatorDatabaseSQL) one(cat *pb.Catalog, name, constName string, q *pb.Query) string {
	var b bytes.Buffer
	params := q.GetParams()
	cols := q.GetColumns()
	retType := "interface{}"
	if len(cols) > 0 {
		for _, c := range cols {
			if t := c.GetTable(); t != nil && t.GetName() != "" && catalogHasTable(cat, t.GetName()) {
				retType = tableNameToGoStruct(t.GetName())
				break
			}
		}
		if retType == "interface{}" {
			retType = name + "Row"
		}
	}

	args := ""
	if len(params) > 0 {
		args = g.namedArgsList(params)
	}
	g.writeFuncSignature(&b, name, params, "(*"+retType+", error)")
	b.WriteString("\ti, err := retry.RetryWithResult(ctx, func(ctx context.Context) (*" + retType + ", error) {\n")
	b.WriteString("\t\trow := q.db.QueryRowContext(ctx, " + constName + args + ")\n")
	b.WriteString("\t\tvar i " + retType + "\n")
	b.WriteString("\t\terr := row.Scan(" + scanTargets(cols) + ")\n")
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t}\n\n")
	b.WriteString("\t\treturn &i, nil\n")
	b.WriteString("\t}, retry.WithLabel(\"" + name + "\"))\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\treturn i, nil\n")
	b.WriteString("}\n")
	return b.String()
}

func (g generatorDatabaseSQL) many(cat *pb.Catalog, name, constName string, q *pb.Query) string {
	var b bytes.Buffer
	params := q.GetParams()
	cols := q.GetColumns()
	rowType := "interface{}"
	if len(cols) > 0 {
		for _, c := range cols {
			if t := c.GetTable(); t != nil && t.GetName() != "" && catalogHasTable(cat, t.GetName()) {
				rowType = tableNameToGoStruct(t.GetName())
				break
			}
		}
		if rowType == "interface{}" {
			rowType = name + "Row"
		}
	}
	args := ""
	if len(params) > 0 {
		args = g.namedArgsList(params)
	}
	g.writeFuncSignature(&b, name, params, "([]"+rowType+", error)")
	b.WriteString("\titems, err := retry.RetryWithResult(ctx, func(ctx context.Context) ([]" + rowType + ", error) {\n")
	if len(params) > 0 {
		b.WriteString("\t\trows, err := q.db.QueryContext(ctx, " + constName + args + ")\n")
	} else {
		b.WriteString("\t\trows, err := q.db.QueryContext(ctx, " + constName + ")\n")
	}
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\treturn nil, err\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\tdefer rows.Close()\n")
	b.WriteString("\t\tvar items []" + rowType + "\n")
	b.WriteString("\t\tfor rows.Next() {\n")
	b.WriteString("\t\t\tvar i " + rowType + "\n")
	b.WriteString("\t\t\tif err := rows.Scan(" + scanTargets(cols) + "); err != nil {\n")
	b.WriteString("\t\t\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t\t}\n")
	b.WriteString("\t\t\titems = append(items, i)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\tif err := rows.Err(); err != nil {\n")
	b.WriteString("\t\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t}\n\n")
	b.WriteString("\t\treturn items, nil\n")
	b.WriteString("\t}, retry.WithLabel(\"" + name + "\"))\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\treturn items, nil\n")
	b.WriteString("}\n")
	return b.String()
}

func (g generatorDatabaseSQL) exec(name, constName string, q *pb.Query) string {
	var b bytes.Buffer
	params := q.GetParams()
	args := ""
	if len(params) > 0 {
		args = g.namedArgsList(params)
	}
	g.writeFuncSignature(&b, name, params, "error")
	b.WriteString("\terr := retry.Retry(ctx, func(ctx context.Context) error {\n")
	if len(params) > 0 {
		b.WriteString("\t\t_, err := q.db.ExecContext(ctx, " + constName + args + ")\n")
	} else {
		b.WriteString("\t\t_, err := q.db.ExecContext(ctx, " + constName + ")\n")
	}
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\treturn xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t}\n\n")
	b.WriteString("\t\treturn nil\n")
	b.WriteString("\t}, retry.WithLabel(\"" + name + "\"))\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn xerrors.WithStackTrace(err)\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n")
	return b.String()
}
