type Options struct {
	Runtime                           string
	EmitSyncQuerier, EmitAsyncQuerier bool
}

func Generate(a *model.AnalysisResult, o Options) ([]model.File, error) {
	if a == nil {
		return nil, fmt.Errorf("python generator: nil analysis result")
	}
	if len(a.Diagnostics) > 0 {
		return nil, fmt.Errorf("python generator: analysis has diagnostics: %s", a.Diagnostics[0])
	}
	if o.Runtime == "" {
		o.Runtime = "ydb"
	}
	if o.Runtime != "ydb" && o.Runtime != "dbapi" && o.Runtime != "sqlalchemy" {
		return nil, fmt.Errorf("python generator: unsupported runtime %q", o.Runtime)
	}
	if o.EmitAsyncQuerier {
		return nil, fmt.Errorf("python generator: async querier is unsupported by the installed YDB Python runtimes; use a synchronous querier")
	}
	for _, q := range a.Queries {
		if err := validateQuery(q); err != nil {
			return nil, err
		}
		if q.Command == model.ExecRows {
			return nil, fmt.Errorf("python generator: query %q: :execrows is unsupported because the selected Python runtime does not expose a portable affected-row count", q.Name)
		}
	}
	if err := validateNames(a); err != nil {
		return nil, err
	}
	m, err := renderModels(a)
	if err != nil {
		return nil, err
	}
	q, err := renderQueries(a, o)
	if err != nil {
		return nil, err
	}
	return []model.File{{Name: "models.py", Content: []byte(strings.TrimRight(m, "\n") + "\n")}, {Name: "queries.py", Content: []byte(strings.TrimRight(q, "\n") + "\n")}, {Name: "__init__.py", Content: []byte("# Code generated by sqlc-ydb. DO NOT EDIT.\n")}}, nil
}

func validateQuery(q model.AnalyzedQuery) error {
	switch q.Command {
	case model.One, model.Many, model.Exec, model.ExecRows:
	default:
		return fmt.Errorf("python generator: query %q: unsupported command %q", q.Name, q.Command)
	}
	if (q.Command == model.One || q.Command == model.Many) && len(q.ResultSets) != 1 {
		return fmt.Errorf("python generator: query %q: expected one result set, got %d", q.Name, len(q.ResultSets))
	}
	for _, p := range q.Parameters {
		if _, err := pyType(p.Type); err != nil {
			return fmt.Errorf("python generator: query %q parameter %q: %w", q.Name, p.Name, err)
		}
	}
	seenParams := map[string]bool{}
	for _, p := range q.Parameters {
		n := fieldName(p.Name)
		if n == "self" {
			return fmt.Errorf("python generator: query %q: parameter name %q conflicts with the generated method receiver", q.Name, n)
		}
		if seenParams[n] {
			return fmt.Errorf("python generator: query %q: parameter name collision at %q", q.Name, n)
		}
		seenParams[n] = true
	}
	for _, rs := range q.ResultSets {
		seenCols := map[string]bool{}
		for _, c := range rs.Columns {
			n := fieldName(c.Name)
			if seenCols[n] {
				return fmt.Errorf("python generator: query %q: column name collision at %q", q.Name, n)
			}
			seenCols[n] = true
			if _, err := pyType(c.Type); err != nil {
				return fmt.Errorf("python generator: query %q column %q: %w", q.Name, c.Name, err)
			}
		}
	}
	return nil
}

func validateNames(a *model.AnalysisResult) error {
	consts, methods, classes := map[string]string{}, map[string]string{}, map[string]string{}
	add := func(dst map[string]string, n, original, kind string) error {
		if prev, ok := dst[n]; ok && prev != original {
			return fmt.Errorf("python generator: %s name collision %q (%q and %q)", kind, n, prev, original)
		}
		dst[n] = original
		return nil
	}
	for _, t := range a.Catalog.Tables {
		n := className(t.Name)
		if prev, ok := classes[n]; ok && prev != "table:"+t.Name {
			return fmt.Errorf("python generator: model name collision %q (%q and %q)", n, prev, t.Name)
		}
		classes[n] = "table:" + t.Name
		seenCols := map[string]bool{}
		for _, c := range t.Columns {
			n := fieldName(c.Name)
			if seenCols[n] {
				return fmt.Errorf("python generator: table %q: column name collision at %q", t.Name, n)
			}
			seenCols[n] = true
		}
	}
	for _, q := range a.Queries {
		if err := add(consts, constName(q.Name), q.Name, "SQL constant"); err != nil {
			return err
		}
		if err := add(methods, methodName(q.Name), q.Name, "method"); err != nil {
			return err
		}
		if q.Command == model.One || q.Command == model.Many {
			n := queryRowClass(a, q)
			sig := resultSignature(q)
			if prev, ok := classes[n]; ok {
				if prev != "table:"+tableForQuery(q) && prev != sig {
					return fmt.Errorf("python generator: row model name collision %q (%q and %q)", n, prev, q.Name)
				}
				if strings.HasPrefix(prev, "table:") {
					classes[n] = sig
				}
			} else {
				classes[n] = sig
			}
		}
	}
	return nil
}

func tableForQuery(q model.AnalyzedQuery) string {
	if len(q.ResultSets) > 0 && len(q.ResultSets[0].Columns) > 0 {
		return q.ResultSets[0].Columns[0].Table
	}
	return ""
}
func resultSignature(q model.AnalyzedQuery) string {
	if len(q.ResultSets) == 0 {
		return ""
	}
	var b strings.Builder
	for _, c := range q.ResultSets[0].Columns {
		b.WriteString(c.Name)
		b.WriteByte(':')
		writeTypeSignature(&b, c.Type)
		b.WriteByte(';')
	}
	return b.String()
}

func writeTypeSignature(b *strings.Builder, t model.Type) {
	b.WriteString(t.Kind)
	if t.Precision != 0 || t.Scale != 0 {
		fmt.Fprintf(b, "(%d,%d)", t.Precision, t.Scale)
	}
	if t.Elem != nil {
		b.WriteByte('<')
		writeTypeSignature(b, *t.Elem)
		b.WriteByte('>')
	}
	if t.Key != nil {
		b.WriteByte('[')
		writeTypeSignature(b, *t.Key)
		b.WriteByte(']')
	}
}

func renderModels(a *model.AnalysisResult) (string, error) {
	var b strings.Builder
	b.WriteString("# Code generated by sqlc-ydb. DO NOT EDIT.\nfrom dataclasses import dataclass\nfrom datetime import date, datetime, timedelta\nfrom uuid import UUID\nfrom typing import Optional\n\n")
	seen := map[string]bool{}
	for _, t := range a.Catalog.Tables {
		n := className(t.Name)
		if seen[n] {
			continue
		}
		seen[n] = true
		b.WriteString("@dataclass\nclass " + n + ":\n")
		if len(t.Columns) == 0 {
			b.WriteString("    pass\n\n")
			continue
		}
		for _, c := range t.Columns {
			typ, e := pyType(c.Type)
			if e != nil {
				return "", e
			}
			b.WriteString("    " + fieldName(c.Name) + ": " + typ + "\n")
		}
		b.WriteString("\n")
	}
	for _, q := range a.Queries {
		if q.Command != model.One && q.Command != model.Many {
			continue
		}
		n := queryRowClass(a, q)
		if seen[n] {
			continue
		}
		seen[n] = true
		b.WriteString("@dataclass\nclass " + n + ":\n")
		if len(q.ResultSets[0].Columns) == 0 {
			b.WriteString("    pass\n\n")
			continue
		}
		for _, c := range q.ResultSets[0].Columns {
			typ, e := pyType(c.Type)
			if e != nil {
				return "", e
			}
			b.WriteString("    " + fieldName(c.Name) + ": " + typ + "\n")
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}

func renderQueries(a *model.AnalysisResult, o Options) (string, error) {
	var b strings.Builder
	b.WriteString("# Code generated by sqlc-ydb. DO NOT EDIT.\nfrom __future__ import annotations\nfrom typing import Iterable, Optional\nfrom . import models\n")
	if o.Runtime == "ydb" {
		b.WriteString("import ydb\n")
	}
	if o.Runtime == "dbapi" {
		b.WriteString("import ydb\n")
	}
	if o.Runtime == "sqlalchemy" {
		b.WriteString("import ydb\nfrom sqlalchemy import text\nfrom sqlalchemy.engine import Connection\n")
	}
	b.WriteString("\n")
	for _, q := range a.Queries {
		sql := q.SQL
		if o.Runtime == "sqlalchemy" {
			var err error
			sql, err = sqlalchemySQL(q)
			if err != nil {
				return "", err
			}
		}
		b.WriteString(constName(q.Name) + " = " + pySQLString(sql) + "\n\n")
	}
	if o.Runtime == "ydb" {
		b.WriteString(ydbTypedHelper)
	} else {
		b.WriteString(tupleTypedHelper)
	}
	if err := renderClass(&b, a, o); err != nil {
		return "", err
	}
	return b.String(), nil
}

func sqlalchemySQL(q model.AnalyzedQuery) (string, error) {
	allowed := map[string]bool{}
	for _, p := range q.Parameters {
		for i, r := range p.Name {
			if !(r == '_' || unicode.IsLetter(r) || i > 0 && unicode.IsDigit(r)) {
				return "", fmt.Errorf("SQLAlchemy parameter name %q is unsupported", p.Name)
			}
		}
		if p.Name == "" {
			return "", fmt.Errorf("empty SQLAlchemy parameter name")
		}
		allowed[p.Name] = true
	}
	lexer := yql.NewYQLLexer(antlr.NewInputStream(q.SQL))
	lexer.RemoveErrorListeners()
	var tokens []antlr.Token
	for token := lexer.NextToken(); token.GetTokenType() != antlr.TokenEOF; token = lexer.NextToken() {
		if token.GetChannel() == antlr.TokenDefaultChannel {
			tokens = append(tokens, token)
		}
	}
	runes := []rune(q.SQL)
	var out strings.Builder
	cursor := 0
	statementStart, inDeclare := true, false
	escape := func(s string) string { return strings.ReplaceAll(s, ":", "\\:") }
	for i, t := range tokens {
		if statementStart {
			inDeclare = t.GetTokenType() == yql.YQLLexerDECLARE
			statementStart = false
		}
		if t.GetTokenType() == yql.YQLLexerSEMICOLON {
			statementStart = true
			continue
		}
		if inDeclare || t.GetTokenType() != yql.YQLLexerDOLLAR || i+1 == len(tokens) {
			continue
		}
		next := tokens[i+1]
		name := strings.Trim(next.GetText(), "`")
		if !allowed[name] {
			continue
		}
		out.WriteString(escape(string(runes[cursor:t.GetStart()])))
		out.WriteString(":" + name)
		cursor = next.GetStop() + 1
	}
	out.WriteString(escape(string(runes[cursor:])))
	return out.String(), nil
}

const ydbTypedHelper = `
def _typed(value, typ):
    return ydb.TypedValue(value, typ)

`
const tupleTypedHelper = `
def _typed(value, typ):
    return (value, typ)

`

func renderClass(b *strings.Builder, a *model.AnalysisResult, o Options) error {
	b.WriteString("\nclass Querier:\n")
	if o.Runtime == "ydb" {
		b.WriteString("    def __init__(self, pool: ydb.QuerySessionPool):\n        self._pool = pool\n\n")
	}
	if o.Runtime == "dbapi" {
		b.WriteString("    def __init__(self, connection):\n        self._connection = connection\n\n")
	}
	if o.Runtime == "sqlalchemy" {
		b.WriteString("    def __init__(self, connection: Connection):\n        self._connection = connection\n\n")
	}
	for _, q := range a.Queries {
		if err := renderMethod(b, a, q, o); err != nil {
			return err
		}
	}
	return nil
}

func renderMethod(b *strings.Builder, a *model.AnalysisResult, q model.AnalyzedQuery, o Options) error {
	typeExprs := make([]string, len(q.Parameters))
	for i, parameter := range q.Parameters {
		var err error
		typeExprs[i], err = ydbTypeExpr(parameter.Type)
		if err != nil {
			return fmt.Errorf("python generator: query %q parameter %q: %w", q.Name, parameter.Name, err)
		}
	}
	p := ""
	for _, x := range q.Parameters {
		t, _ := pyType(x.Type)
		p += ", " + fieldName(x.Name) + ": " + t
	}
	ret := "None"
	row := queryRowClass(a, q)
	if q.Command == model.One {
		ret = "Optional[models." + row + "]"
	}
	if q.Command == model.Many {
		ret = "Iterable[models." + row + "]"
	}
	indent := "        "
	if o.Runtime == "dbapi" {
		indent = "            "
	}
	b.WriteString("    def " + methodName(q.Name) + "(self" + p + ") -> " + ret + ":\n")
	if o.Runtime == "ydb" {
		b.WriteString("        parameters = {")
		for i, x := range q.Parameters {
			if i > 0 {
				b.WriteString(",")
			}
			value := "_typed(" + fieldName(x.Name) + ", " + typeExprs[i] + ")"
			b.WriteString(pyString("$"+x.Name) + ": " + value)
		}
		b.WriteString("}\n        result_sets = self._pool.execute_with_retries(" + constName(q.Name) + ", parameters)\n")
	}
	if o.Runtime == "dbapi" {
		b.WriteString("        parameters = {")
		for i, x := range q.Parameters {
			if i > 0 {
				b.WriteString(",")
			}
			b.WriteString(pyString("$"+x.Name) + ": _typed(" + fieldName(x.Name) + ", " + typeExprs[i] + ")")
		}
		b.WriteString("}\n        cursor = self._connection.cursor()\n        try:\n            cursor.execute(" + constName(q.Name) + ", parameters)\n")
	}
	if o.Runtime == "sqlalchemy" {
		b.WriteString("        parameters = {")
		for i, x := range q.Parameters {
			if i > 0 {
				b.WriteString(",")
			}
			b.WriteString(pyString(x.Name) + ": _typed(" + fieldName(x.Name) + ", " + typeExprs[i] + ")")
		}
		b.WriteString("}\n        result = ")
		b.WriteString("self._connection.execute(text(" + constName(q.Name) + "), parameters)\n")
	}
	if q.Command == model.One || q.Command == model.Many {
		if o.Runtime == "ydb" {
			b.WriteString(indent + "rows = result_sets[0].rows\n")
		} else if o.Runtime == "dbapi" {
			b.WriteString(indent + "rows = cursor.fetchall()\n")
		} else {
			b.WriteString(indent + "try:\n" + indent + "    rows = result.fetchall()\n" + indent + "finally:\n" + indent + "    result.close()\n")
		}
		if q.Command == model.One {
			b.WriteString(indent + "if not rows:\n" + indent + "    return None\n" + indent + "row = rows[0]\n" + indent + "return models." + row + "(\n")
			for i, c := range q.ResultSets[0].Columns {
				b.WriteString(indent + "    " + fieldName(c.Name) + "=" + rowValue(o.Runtime, c.ResultName(), i) + ",\n")
			}
			b.WriteString(indent + ")\n")
		} else {
			b.WriteString(indent + "return (models." + row + "(\n")
			for i, c := range q.ResultSets[0].Columns {
				b.WriteString(indent + "    " + fieldName(c.Name) + "=" + rowValue(o.Runtime, c.ResultName(), i) + ",\n")
			}
			b.WriteString(indent + ") for row in rows)\n")
		}
	} else {
		if o.Runtime == "dbapi" {
			b.WriteString(indent + "return None\n")
		} else if o.Runtime == "sqlalchemy" {
			b.WriteString("        result.close()\n        return None\n")
		} else {
			b.WriteString("        return None\n")
		}
	}
	if o.Runtime == "dbapi" {
		b.WriteString("        finally:\n            cursor.close()\n")
	}
	b.WriteString("\n")
	return nil
}

func rowValue(runtime, name string, index int) string {
	switch runtime {
	case "ydb":
		return "row[" + pyString(name) + "]"
	case "dbapi":
		return "row[" + strconv.Itoa(index) + "]"
	default:
		return "row._mapping[" + pyString(name) + "]"
	}
}

func queryRowClass(a *model.AnalysisResult, q model.AnalyzedQuery) string {
	if len(q.ResultSets) > 0 && len(q.ResultSets[0].Columns) > 0 {
		table := q.ResultSets[0].Columns[0].Table
		if table != "" && a != nil && queryMatchesTable(a, q, table) {
			return className(singularize(table))
		}
	}
	return className(q.Name + "Row")
}

func queryMatchesTable(a *model.AnalysisResult, q model.AnalyzedQuery, table string) bool {
	for _, t := range a.Catalog.Tables {
		if t.Name != table {
			continue
		}
		cols := q.ResultSets[0].Columns
		if len(cols) != len(t.Columns) {
			return false
		}
		for i, c := range cols {
			if c.Name != t.Columns[i].Name || resultTypeSignature(c.Type) != resultTypeSignature(t.Columns[i].Type) {
				return false
			}
		}
		return true
	}
	return false
}
func resultTypeSignature(t model.Type) string {
	var b strings.Builder
	writeTypeSignature(&b, t)
	return b.String()
}

func pyType(t model.Type) (string, error) {
	if t.IsOptional() {
		if t.Elem == nil {
			return "", fmt.Errorf("malformed Optional type")
		}
		x, e := pyType(*t.Elem)
		return "Optional[" + x + "]", e
	}
	kind := strings.ToLower(t.Kind)
	if primitive, ok := pythonPrimitiveTypes[kind]; ok {
		return primitive.python, nil
	}
	switch kind {
	case "list":
		if t.Elem == nil {
			return "", fmt.Errorf("List without element type")
		}
		x, e := pyType(*t.Elem)
		return "list[" + x + "]", e
	case "set":
		if t.Elem == nil {
			return "", fmt.Errorf("Set without element type")
		}
		x, e := pyType(*t.Elem)
		return "set[" + x + "]", e
	case "dict":
		if t.Key == nil || t.Elem == nil {
			return "", fmt.Errorf("Dict without key/value type")
		}
		k, e := pyType(*t.Key)
		if e != nil {
			return "", e
		}
		v, e := pyType(*t.Elem)
		return "dict[" + k + ", " + v + "]", e
	default:
		return "", fmt.Errorf("unsupported YQL type %q", t.Kind)
	}
}

func ydbTypeExpr(t model.Type) (string, error) {
	if t.IsOptional() {
		if t.Elem == nil {
			return "", fmt.Errorf("malformed Optional type")
		}
		elem, err := ydbTypeExpr(*t.Elem)
		return "ydb.OptionalType(" + elem + ")", err
	}
	kind := strings.ToLower(t.Kind)
	if primitive, ok := pythonPrimitiveTypes[kind]; ok {
		return "ydb.PrimitiveType." + primitive.ydb, nil
	}
	if kind == "list" || kind == "set" {
		if t.Elem == nil {
			return "", fmt.Errorf("%s without element type", t.Kind)
		}
		elem, err := ydbTypeExpr(*t.Elem)
		if err != nil {
			return "", err
		}
		constructor := "ListType"
		if kind == "set" {
			constructor = "SetType"
		}
		return "ydb." + constructor + "(" + elem + ")", nil
	}
	if kind == "dict" {
		if t.Key == nil || t.Elem == nil {
			return "", fmt.Errorf("Dict without key/value type")
		}
		key, err := ydbTypeExpr(*t.Key)
		if err != nil {
			return "", err
		}
		elem, err := ydbTypeExpr(*t.Elem)
		if err != nil {
			return "", err
		}
		return "ydb.DictType(" + key + ", " + elem + ")", nil
	}
	return "", fmt.Errorf("unsupported YQL type %q", t.Kind)
}

