func pyString(s string) string { return strconv.Quote(s) }

func pySQLString(s string) string {
	lines := strings.SplitAfter(s, "\n")
	parts := make([]string, 0, len(lines))
	for _, line := range lines {
		if line != "" {
			parts = append(parts, pyString(line))
		}
	}
	if len(parts) == 0 {
		return `""`
	}
	return "(" + strings.Join(parts, "\n             ") + ")"
}

func methodName(s string) string { return fieldName(s) }
func className(s string) string {
	x := snake(s)
	if x == "" {
		x = "row"
	}
	parts := strings.Split(x, "_")
	for i, p := range parts {
		if p != "" {
			r, size := utf8.DecodeRuneInString(p)
			parts[i] = string(unicode.ToUpper(r)) + p[size:]
		}
	}
	return strings.Join(parts, "")
}

func validPythonName(name string) bool {
	if name == "" || pythonKeywords[name] {
		return false
	}
	for i, r := range name {
		if r != '_' && !unicode.IsLetter(r) && (i == 0 || !unicode.IsDigit(r)) {
			return false
		}
	}
	return true
}

func fieldName(s string) string {
	x := snake(s)
	if x == "" {
		x = "value"
	}
	if pythonKeywords[x] {
		x += "_"
	}
	return x
}
func snake(s string) string {
	var b strings.Builder
	last := false
	for _, r := range s {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			if unicode.IsUpper(r) && b.Len() > 0 && !last {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
			last = false
		} else if !last {
			b.WriteByte('_')
			last = true
		}
	}
	return strings.Trim(b.String(), "_")
}

