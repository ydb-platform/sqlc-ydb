func pyString(s string) string { return strconv.Quote(s) }

func pySQLString(s string) string {
	var b strings.Builder
	b.WriteString(`"""`)
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\r':
			b.WriteString(`\r`)
		case '\n', '\t':
			b.WriteRune(r)
		default:
			if unicode.IsControl(r) {
				quoted := strconv.QuoteRune(r)
				b.WriteString(quoted[1 : len(quoted)-1])
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteString(`"""`)
	return b.String()
}
func constName(s string) string {
	x := strings.ToUpper(snake(s))
	if x == "" {
		x = "QUERY"
	}
	return "SQL_" + x
}
func methodName(s string) string { return fieldName(s) }
func className(s string) string {
	x := snake(s)
	if x == "" {
		x = "row"
	}
	parts := strings.Split(x, "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func singularize(s string) string {
	x := strings.ToLower(s)
	if strings.HasSuffix(x, "ies") && len(x) > 3 {
		return x[:len(x)-3] + "y"
	}
	if strings.HasSuffix(x, "ses") && len(x) > 3 {
		return x[:len(x)-2]
	}
	if strings.HasSuffix(x, "s") && !strings.HasSuffix(x, "ss") && len(x) > 1 {
		return x[:len(x)-1]
	}
	return x
}
func fieldName(s string) string {
	x := snake(s)
	if x == "" {
		x = "value"
	}
	if pythonKeywords[x] {
		x += "_"
	}
	return x
}
func snake(s string) string {
	var b strings.Builder
	last := false
	for _, r := range s {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			if unicode.IsUpper(r) && b.Len() > 0 && !last {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
			last = false
		} else if !last {
			b.WriteByte('_')
			last = true
		}
	}
	return strings.Trim(b.String(), "_")
}

