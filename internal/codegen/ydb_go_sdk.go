package codegen

import (
	"bytes"
	"context"
	"strings"
	"text/template"

	"github.com/sqlc-dev/sqlc-engine-ydb/internal/codegen/pb"
)

var _ Generator = generatorGoSdk{}

type generatorGoSdk struct{}

func (g generatorGoSdk) Name() string {
	return "ydb-go-sdk"
}

func (g generatorGoSdk) Generate(ctx context.Context, req *pb.GenerateRequest) (*pb.GenerateResponse, error) {
	opts, err := parseOptions(req.GetPluginOptions())
	if err != nil {
		return nil, err
	}
	pkg := opts.Package
	if pkg == "" {
		pkg = "db"
	}
	sqlPkg := opts.SQLPackage
	outDir := "."
	if s := req.GetSettings(); s != nil && s.GetCodegen() != nil {
		outDir = s.GetCodegen().GetOut()
	}
	if outDir == "" {
		outDir = "."
	}

	var files []*pb.File

	models, err := g.models(req.GetCatalog(), req.GetQueries(), pkg)
	if err != nil {
		return nil, err
	}
	files = append(files, &pb.File{Name: "models.go", Contents: models})

	db, err := g.db(pkg, sqlPkg)
	if err != nil {
		return nil, err
	}
	files = append(files, &pb.File{Name: "db.go", Contents: db})

	byFilename := make(map[string][]*pb.Query)
	for _, q := range req.GetQueries() {
		fn := q.GetFilename()
		if fn == "" {
			fn = "query.sql"
		}
		if idx := strings.LastIndex(fn, "/"); idx >= 0 {
			fn = fn[idx+1:]
		}
		byFilename[fn] = append(byFilename[fn], q)
	}
	for fname, qs := range byFilename {
		outName := strings.TrimSuffix(fname, ".sql") + ".sql.go"
		if outName == fname {
			outName = "query.sql.go"
		}
		content, err := g.queries(req.GetCatalog(), pkg, sqlPkg, fname, qs)
		if err != nil {
			return nil, err
		}
		files = append(files, &pb.File{Name: outName, Contents: content})
	}

	return &pb.GenerateResponse{Files: files}, nil
}

func (g generatorGoSdk) models(cat *pb.Catalog, queries []*pb.Query, pkg string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sqlc. DO NOT EDIT.\n")
	buf.WriteString("package " + pkg + "\n\n")

	for _, schema := range cat.GetSchemas() {
		for _, tbl := range schema.GetTables() {
			name := tbl.GetRel().GetName()
			if name == "" {
				continue
			}
			structName := tableNameToGoStruct(name)
			buf.WriteString("type " + structName + " struct {\n")
			for _, col := range tbl.GetColumns() {
				yt := ydbTypeName(col)
				goType := goTypeFromYDB(yt, col.GetNotNull())
				fname := toGoField(col.GetName())
				buf.WriteString("\t" + fname + " " + goType + " `json:\"" + col.GetName() + "\"`\n")
			}
			buf.WriteString("}\n\n")
		}
	}

	hasCatalogTables := false
	for _, s := range cat.GetSchemas() {
		if len(s.GetTables()) > 0 {
			hasCatalogTables = true
			break
		}
	}
	if !hasCatalogTables {
		for _, q := range queries {
			cols := q.GetColumns()
			if len(cols) == 0 {
				continue
			}
			cmd := strings.ToLower(q.GetCmd())
			if cmd != ":one" && cmd != ":many" {
				continue
			}
			name := q.GetName() + "Row"
			buf.WriteString("type " + name + " struct {\n")
			for _, col := range cols {
				yt := ydbTypeName(col)
				goType := goTypeFromYDB(yt, col.GetNotNull())
				fname := toGoField(col.GetName())
				buf.WriteString("\t" + fname + " " + goType + " `json:\"" + col.GetName() + "\"`\n")
			}
			buf.WriteString("}\n\n")
		}
	}
	return buf.Bytes(), nil
}

func (g generatorGoSdk) db(pkg, sqlPkg string) ([]byte, error) {
	const ydbDBTemplate = `// Code generated by sqlc. DO NOT EDIT.
package {{.Package}}

import (
	"context"

	"{{.SQLPkg}}/query"
)

type DBTX interface {
	Exec(ctx context.Context, sql string, opts ...query.ExecuteOption) error
	Query(ctx context.Context, sql string, opts ...query.ExecuteOption) (query.Result, error)
	QueryResultSet(ctx context.Context, sql string, opts ...query.ExecuteOption) (query.ClosableResultSet, error)
	QueryRow(ctx context.Context, sql string, opts ...query.ExecuteOption) (query.Row, error)
}

func New(db DBTX) *Queries {
	return &Queries{db: db}
}

type Queries struct {
	db DBTX
}
`

	t := template.Must(template.New("db").Parse(ydbDBTemplate))
	var buf bytes.Buffer
	if err := t.Execute(&buf, map[string]string{"Package": pkg, "SQLPkg": sqlPkg}); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func (g generatorGoSdk) queries(cat *pb.Catalog, pkg, sqlPkg, sourceName string, queries []*pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sqlc. DO NOT EDIT.\n// source: " + sourceName + "\n\n")
	buf.WriteString("package " + pkg + "\n\n")
	buf.WriteString("import (\n\t\"context\"\n\n\tydb \"" + sqlPkg + "\"\n\t\"" + sqlPkg + "/pkg/xerrors\"\n\t\"" + sqlPkg + "/query\"\n)\n\n")

	for _, q := range queries {
		block, err := g.query(cat, pkg, sqlPkg, q)
		if err != nil {
			return nil, err
		}
		buf.Write(block)
		buf.WriteString("\n")
	}
	return buf.Bytes(), nil
}

func (g generatorGoSdk) query(cat *pb.Catalog, pkg, sqlPkg string, q *pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	name := q.GetName()
	cmd := strings.ToLower(q.GetCmd())
	text := q.GetText()

	constName := toGoConst(name)
	buf.WriteString("const " + constName + " = `" + text + "`\n\n")

	switch cmd {
	case ":one":
		buf.WriteString(g.one(cat, name, constName, q, sqlPkg))
	case ":many":
		buf.WriteString(g.many(cat, name, constName, q, sqlPkg))
	case ":exec":
		buf.WriteString(g.exec(name, constName, q, sqlPkg))
	default:
		buf.WriteString(g.exec(name, constName, q, sqlPkg))
	}
	return buf.Bytes(), nil
}

// goParamList returns "id uint64, name string, bio *string" for method signature.
func (g generatorGoSdk) goParamList(params []*pb.Parameter) string {
	var parts []string
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		yt := ydbTypeName(col)
		goType := goTypeFromYDB(yt, col.GetNotNull())
		parts = append(parts, toGoParamName(col.GetName())+" "+goType)
	}
	return strings.Join(parts, ", ")
}

// writeFuncSignature writes a multi-line signature when params exist: ctx on first line, each param on its own line, opts, then return type.
func (g generatorGoSdk) writeFuncSignature(b *bytes.Buffer, name string, params []*pb.Parameter, returnType string) {
	if len(params) == 0 {
		b.WriteString("func (q *Queries) " + name + "(ctx context.Context, opts ...query.ExecuteOption) " + returnType + " {\n")
		return
	}
	b.WriteString("func (q *Queries) " + name + "(ctx context.Context,\n")
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		yt := ydbTypeName(col)
		goType := goTypeFromYDB(yt, col.GetNotNull())
		b.WriteString("\t" + toGoParamName(col.GetName()) + " " + goType + ",\n")
	}
	b.WriteString("\topts ...query.ExecuteOption,\n")
	b.WriteString(") " + returnType + " {\n")
}

func (g generatorGoSdk) paramMethod(yt string, _ bool) string {
	switch yt {
	case "uint64":
		return "Uint64"
	case "int64":
		return "Int64"
	case "uint32":
		return "Uint32"
	case "int32":
		return "Int32"
	case "utf8", "string", "text":
		return "Text"
	case "bool", "boolean":
		return "Bool"
	case "float", "double":
		return "Double"
	default:
		return "Text"
	}
}

// inlineParamsChain returns the chained ParamsBuilder expression for use inside query.WithParameters(...).
func (g generatorGoSdk) inlineParamsChain(params []*pb.Parameter) string {
	var parts []string
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		pn := "$" + col.GetName()
		yt := ydbTypeName(col)
		notNull := col.GetNotNull()
		argName := toGoParamName(col.GetName())
		if notNull {
			parts = append(parts, "Param(\""+pn+"\")."+g.paramMethod(yt, notNull)+"("+argName+")")
		} else {
			parts = append(parts, "Param(\""+pn+"\").BeginOptional()."+g.paramMethod(yt, false)+"("+argName+").EndOptional()")
		}
	}
	if len(parts) == 0 {
		return "ydb.ParamsBuilder().Build()"
	}
	return "ydb.ParamsBuilder().\n\t\t\t\t" + strings.Join(parts, ".\n\t\t\t\t") + ".\n\t\t\t\tBuild()"
}

func (g generatorGoSdk) one(cat *pb.Catalog, name, constName string, q *pb.Query, sqlPkg string) string {
	var b bytes.Buffer
	params := q.GetParams()
	cols := q.GetColumns()
	retType := "interface{}"
	if len(cols) > 0 {
		for _, c := range cols {
			if t := c.GetTable(); t != nil && t.GetName() != "" && catalogHasTable(cat, t.GetName()) {
				retType = tableNameToGoStruct(t.GetName())
				break
			}
		}
		if retType == "interface{}" {
			retType = name + "Row"
		}
	}

	g.writeFuncSignature(&b, name, params, "(*"+retType+", error)")
	if len(params) > 0 {
		b.WriteString("\trow, err := q.db.QueryRow(ctx, " + constName + ",\n")
		b.WriteString("\t\tappend(opts,\n")
		b.WriteString("\t\t\tquery.WithParameters(\n")
		b.WriteString("\t\t\t\t" + g.inlineParamsChain(params) + ",\n")
		b.WriteString("\t\t\t),\n")
		b.WriteString("\t\t\tquery.WithLabel(\"" + name + "\"),\n")
		b.WriteString("\t\t)...,\n")
		b.WriteString("\t)\n")
	} else {
		b.WriteString("\trow, err := q.db.QueryRow(ctx, " + constName + ",\n")
		b.WriteString("\t\tappend(opts, query.WithLabel(\"" + name + "\"))...,\n")
		b.WriteString("\t)\n")
	}
	b.WriteString("\tif err != nil {\n\t\treturn nil, xerrors.WithStackTrace(err)\n\t}\n")
	b.WriteString("\n")
	b.WriteString("\tvar i " + retType + "\n")
	b.WriteString("\terr = row.Scan(" + scanTargets(cols) + ")\n")
	b.WriteString("\tif err != nil {\n\t\treturn nil, xerrors.WithStackTrace(err)\n\t}\n")
	b.WriteString("\n")
	b.WriteString("\treturn &i, nil\n}\n\n")
	return b.String()
}

func (g generatorGoSdk) many(cat *pb.Catalog, name, constName string, q *pb.Query, sqlPkg string) string {
	var b bytes.Buffer
	params := q.GetParams()
	cols := q.GetColumns()
	rowType := "interface{}"
	if len(cols) > 0 {
		for _, c := range cols {
			if t := c.GetTable(); t != nil && t.GetName() != "" && catalogHasTable(cat, t.GetName()) {
				rowType = tableNameToGoStruct(t.GetName())
				break
			}
		}
		if rowType == "interface{}" {
			rowType = name + "Row"
		}
	}
	g.writeFuncSignature(&b, name, params, "([]"+rowType+", error)")
	if len(params) > 0 {
		b.WriteString("\tresult, err := q.db.QueryResultSet(ctx, " + constName + ",\n")
		b.WriteString("\t\tappend(opts,\n")
		b.WriteString("\t\t\tquery.WithParameters(\n")
		b.WriteString("\t\t\t\t" + g.inlineParamsChain(params) + ",\n")
		b.WriteString("\t\t\t),\n")
		b.WriteString("\t\t\tquery.WithLabel(\"" + name + "\"),\n")
		b.WriteString("\t\t)...,\n")
		b.WriteString("\t)\n")
	} else {
		b.WriteString("\tresult, err := q.db.QueryResultSet(ctx, " + constName + ",\n")
		b.WriteString("\t\tappend(opts, query.WithLabel(\"" + name + "\"))...,\n")
		b.WriteString("\t)\n")
	}
	b.WriteString("\tif err != nil {\n\t\treturn nil, xerrors.WithStackTrace(err)\n\t}\n")
	b.WriteString("\n")
	b.WriteString("\tvar items []" + rowType + "\n")
	b.WriteString("\tfor row, err := range result.Rows(ctx) {\n")
	b.WriteString("\t\tif err != nil {\n\t\t\treturn nil, xerrors.WithStackTrace(err)\n\t\t}\n")
	b.WriteString("\n")
	b.WriteString("\t\tvar i " + rowType + "\n")
	b.WriteString("\t\tif err := row.Scan(" + scanTargets(cols) + "); err != nil {\n\t\t\treturn nil, xerrors.WithStackTrace(err)\n\t\t}\n")
	b.WriteString("\t\titems = append(items, i)\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif err := result.Close(ctx); err != nil {\n\t\treturn nil, xerrors.WithStackTrace(err)\n\t}\n")
	b.WriteString("\n")
	b.WriteString("\treturn items, nil\n}\n\n")
	return b.String()
}

func (g generatorGoSdk) exec(name, constName string, q *pb.Query, sqlPkg string) string {
	var b bytes.Buffer
	params := q.GetParams()
	g.writeFuncSignature(&b, name, params, "error")
	if len(params) > 0 {
		b.WriteString("\terr := q.db.Exec(ctx, " + constName + ",\n")
		b.WriteString("\t\tappend(opts,\n")
		b.WriteString("\t\t\tquery.WithParameters(\n")
		b.WriteString("\t\t\t\t" + g.inlineParamsChain(params) + ",\n")
		b.WriteString("\t\t\t),\n")
		b.WriteString("\t\t\tquery.WithLabel(\"" + name + "\"),\n")
		b.WriteString("\t\t)...,\n")
		b.WriteString("\t)\n")
	} else {
		b.WriteString("\terr := q.db.Exec(ctx, " + constName + ",\n")
		b.WriteString("\t\tappend(opts, query.WithLabel(\"" + name + "\"))...,\n")
		b.WriteString("\t)\n")
	}
	b.WriteString("\tif err != nil {\n\t\treturn xerrors.WithStackTrace(err)\n\t}\n")
	b.WriteString("\n")
	b.WriteString("\treturn nil\n}\n\n")
	return b.String()
}
