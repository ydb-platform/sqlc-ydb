func phpSQLString(value, indent string) string {
	if value == "" {
		return "''"
	}
	if canUseNowdoc(value) {
		delimiter := "SQLC_YDB_YQL"
		for suffix := 2; strings.Contains(value, delimiter); suffix++ {
			delimiter = fmt.Sprintf("SQLC_YDB_YQL_%d", suffix)
		}
		ending := ""
		if strings.HasSuffix(value, "\r\n") {
			ending = ` . "\r\n"`
		} else if strings.HasSuffix(value, "\n") {
			ending = ` . "\n"`
		}
		separator := "\n"
		if strings.HasSuffix(value, "\n") {
			separator = ""
		}
		return "<<<'" + delimiter + "'\n" + value + separator + delimiter + ending
	}
	return escapedPHPString(value, indent)
}

func phpString(value, indent string) string { return escapedPHPString(value, indent) }

func canUseNowdoc(value string) bool {
	for i, r := range value {
		if r == '\r' {
			if i+1 >= len(value) || value[i+1] != '\n' {
				return false
			}
			continue
		}
		if (r < 0x20 && r != '\n' && r != '\t') || r == 0x7f {
			return false
		}
	}
	return true
}

func escapedPHPString(value, indent string) string {
	parts := make([]string, 0, 4)
	var text strings.Builder
	flush := func() {
		if text.Len() == 0 {
			return
		}
		parts = append(parts, "'"+text.String()+"'")
		text.Reset()
	}
	for _, r := range value {
		switch r {
		case '\\':
			text.WriteString(`\\`)
		case '\'':
			text.WriteString(`\'`)
		case '\n', '\r', '\t', 0:
			flush()
			escape := map[rune]string{'\n': `"\n"`, '\r': `"\r"`, '\t': `"\t"`, 0: `"\x00"`}[r]
			parts = append(parts, escape)
		default:
			if r < 0x20 || r == 0x7f {
				flush()
				parts = append(parts, fmt.Sprintf(`"\x%02x"`, r))
			} else {
				text.WriteRune(r)
			}
		}
	}
	flush()
	if len(parts) == 0 {
		return "''"
	}
	if indent == "" || len(parts) == 1 {
		return strings.Join(parts, " . ")
	}
	return strings.Join(parts, " .\n"+indent)
}

func words(value string) []string {
	var out []string
	runes := []rune(value)
	start := -1
	flush := func(end int) {
		if start >= 0 && start < end {
			out = append(out, strings.ToLower(string(runes[start:end])))
		}
		start = -1
	}
	for i, r := range runes {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			flush(i)
			continue
		}
		if start < 0 {
			start = i
			continue
		}
		prev := runes[i-1]
		if unicode.IsUpper(r) && (unicode.IsLower(prev) || unicode.IsDigit(prev)) {
			flush(i)
			start = i
		}
	}
	flush(len(runes))
	return out
}

func pascalName(value string) string {
	parts := words(value)
	for i, part := range parts {
		first, size := utf8.DecodeRuneInString(part)
		parts[i] = string(unicode.ToUpper(first)) + part[size:]
	}
	return strings.Join(parts, "")
}

func camelName(value string) string {
	name := pascalName(value)
	if name == "" {
		return ""
	}
	first, size := utf8.DecodeRuneInString(name)
	return string(unicode.ToLower(first)) + name[size:]
}

func screamingName(value string) string { return strings.ToUpper(strings.Join(words(value), "_")) }

func validNamespace(value string) bool {
	parts := strings.Split(value, `\`)
	for _, part := range parts {
		if !validPHPIdentifier(part) || phpReserved[strings.ToLower(part)] {
			return false
		}
	}
	return true
}

func validPHPIdentifier(value string) bool {
	if value == "" {
		return false
	}
	for i, r := range value {
		if !(r == '_' || unicode.IsLetter(r) || (i > 0 && unicode.IsDigit(r))) {
			return false
		}
	}
	return true
}

