// jooqType uses the YDB dialect's native carriers and bindings.
func jooqType(t model.Type) (string, string, error) {
	kinds := map[string]string{"Bool": "Boolean", "Int8": "Byte", "Int16": "Short", "Int32": "Integer", "Int64": "Long", "Uint8": "org.jooq.types.UByte", "Uint16": "org.jooq.types.UShort", "Uint32": "org.jooq.types.UInteger", "Uint64": "org.jooq.types.ULong", "Float": "Float", "Double": "Double", "Utf8": "String", "String": "byte[]", "Json": "org.jooq.JSON", "JsonDocument": "org.jooq.JSONB", "Timestamp": "java.time.Instant", "Date": "java.time.LocalDate", "Datetime": "java.time.LocalDateTime", "Interval": "java.time.Duration", "Uuid": "java.util.UUID"}
	k := t.UnwrapOptional().Kind
	typ, ok := kinds[k]
	if !ok {
		return "", "", fmt.Errorf("jOOQ does not support type %s", t.String())
	}
	return typ, "YdbTypes." + strings.ToUpper(k), nil
}
func jooqConstant(s string) (string, error) {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' || r == '.' })
	for i, part := range parts {
		n, err := name(part, true)
		if err != nil {
			return "", err
		}
		parts[i] = strings.ToUpper(n)
	}
	result := strings.Join(parts, "_")
	if !identifier(result) {
		return "", fmt.Errorf("invalid jOOQ identifier %q", s)
	}
	return result, nil
}

func jooqTableConstant(path string) (string, error) {
	return jooqConstant(strings.ReplaceAll(path, "/", "_"))
}

func generateJooq(a *model.AnalysisResult, o Options) ([]model.File, error) {
	header := "// Code generated by sqlc-ydb. DO NOT EDIT.\npackage " + o.Package + ";\n\n"
	files := []model.File{}
	var tables strings.Builder
	tables.WriteString(header + "import org.jooq.Record;\nimport org.jooq.Table;\nimport org.jooq.TableField;\nimport org.jooq.impl.TableImpl;\nimport tech.ydb.jooq.YdbTypes;\n\nimport static org.jooq.impl.DSL.name;\n\npublic final class Tables {\n    private Tables() {}\n")
	tableNames := map[string]bool{}
	for _, t := range a.Catalog.Tables {
		cn, err := tableName(t.Name)
		if err != nil {
			return nil, err
		}
		cn += "Table"
		constant, err := jooqTableConstant(t.Name)
		if err != nil {
			return nil, err
		}
		if tableNames[cn] || tableNames[constant] {
			return nil, fmt.Errorf("jOOQ table name collision: %s", t.Name)
		}
		tableNames[cn] = true
		tableNames[constant] = true
		fmt.Fprintf(&tables, "\n    public static final %s %s = new %s(%s, null);\n\n    public static final class %s extends TableImpl<Record> {\n", cn, constant, cn, quoted(t.Name), cn)
		fields := map[string]bool{}
		for _, c := range t.Columns {
			fn, err := jooqConstant(c.Name)
			if err != nil {
				return nil, err
			}
			if fields[fn] {
				return nil, fmt.Errorf("jOOQ field collision in %s: %s", t.Name, fn)
			}
			fields[fn] = true
			typ, dt, err := jooqType(c.Type)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&tables, "        public final TableField<Record, %s> %s = createField(name(%s), %s.nullable(%t), this);\n", typ, fn, quoted(c.Name), dt, c.Type.IsOptional())
		}
		fmt.Fprintf(&tables, "\n        private %s(String name, Table<Record> aliased) {\n            super(name(name), null, aliased);\n        }\n\n        @Override\n        public %s as(String alias) {\n            return new %s(alias, this);\n        }\n    }\n", cn, cn, cn)
	}
	tables.WriteString("}\n")
	files = append(files, model.File{Name: "Tables.java", Content: []byte(tables.String())})
	embeddedTables := map[string]bool{}
	for _, q := range a.Queries {
		for _, result := range q.ResultSets {
			for _, embed := range result.Embeds {
				embeddedTables[embed.Table] = true
			}
		}
	}
	modelNames := map[string]bool{"Queries": true, "Tables": true}
	for _, table := range a.Catalog.Tables {
		if !embeddedTables[table.Name] {
			continue
		}
		n, err := tableName(table.Name)
		if err != nil {
			return nil, err
		}
		if modelNames[n] {
			return nil, fmt.Errorf("jOOQ model name collision: %s", n)
		}
		modelNames[n] = true
		fields := []string{}
		seen := map[string]bool{}
		for _, column := range table.Columns {
			field, err := name(column.Name, false)
			if err != nil {
				return nil, err
			}
			if seen[field] {
				return nil, fmt.Errorf("jOOQ field name collision in %s: %s", n, field)
			}
			seen[field] = true
			typ, _, err := jooqType(column.Type)
			if err != nil {
				return nil, err
			}
			fields = append(fields, typ+" "+field)
		}
		files = append(files, model.File{Name: n + ".java", Content: []byte(header + "public record " + n + "(" + strings.Join(fields, ", ") + ") {}\n")})
	}
	var b strings.Builder
	b.WriteString(header + "import java.util.List;\nimport java.util.Objects;\nimport java.util.Optional;\n\nimport org.jooq.impl.SQLDataType;\nimport tech.ydb.jooq.YdbDSLContext;\nimport tech.ydb.jooq.YdbTypes;\n\n" + batchImports(a) + "import static org.jooq.impl.DSL.*;\nimport static org.jooq.Records.mapping;\nimport static " + o.Package + ".Tables.*;\n\npublic final class Queries {\n    private final YdbDSLContext dsl;\n\n    public Queries(YdbDSLContext dsl) {\n        this.dsl = Objects.requireNonNull(dsl);\n    }\n")
	methods := map[string]bool{}
	for _, q := range a.Queries {
		if hasStructList(q) {
			if q.Command != model.Exec {
				return nil, fmt.Errorf("%s: jOOQ List<Struct> parameters require :exec", q.Name)
			}
			method, err := name(q.Name, false)
			if err != nil {
				return nil, err
			}
			if methods[method] {
				return nil, fmt.Errorf("Java method name collision: %s", method)
			}
			methods[method] = true
			// Reuse the JDBC DTO validation and binding contract for structured input.
			generated, err := Generate(&model.AnalysisResult{Queries: []model.AnalyzedQuery{q}}, Options{Package: o.Package, Runtime: "jdbc"})
			if err != nil {
				return nil, err
			}
			for _, file := range generated {
				if file.Name == "Queries.java" {
					continue
				}
				for _, existing := range files {
					if existing.Name == file.Name {
						return nil, fmt.Errorf("Java type name collision: %s", file.Name)
					}
				}
				files = append(files, file)
			}
			var parameters, names []string
			for _, p := range q.Parameters {
				pn, _ := name(p.Name, false)
				_, typ, _ := typeInfo(p.Type)
				if isStructList(p.Type) {
					qn, _ := name(q.Name, true)
					n, _ := name(p.Name, true)
					typ = "java.util.List<" + qn + n + "Item>"
				}
				parameters = append(parameters, typ+" "+pn)
				names = append(names, pn)
			}
			fmt.Fprintf(&b, "\n    // %s\n    public void %s(%s) {\n", model.QueryAnnotation(q), method, strings.Join(parameters, ", "))
			emitUnsignedChecks(&b, q, names)
			b.WriteString("        dsl.connection(_connection -> {\n")
			text, bindings := jdbc.SQL(q)
			mappedSQL, err := jooqBatchSQL(q, text)
			if err != nil {
				return nil, err
			}
			emitJDBCOn(&b, q, names, bindings, mappedSQL, "", "_connection", "            ")
			b.WriteString("        });\n    }\n")
			continue
		}
		if q.Syntax == nil {
			return nil, fmt.Errorf("%s: jOOQ requires analyzed YQL syntax", q.Name)
		}
		method, err := name(q.Name, false)
		if err != nil {
			return nil, err
		}
		if methods[method] {
			return nil, fmt.Errorf("Java method name collision: %s", method)
		}
		methods[method] = true
		row, err := name(q.Name+"Row", true)
		if err != nil {
			return nil, err
		}
		ret := "void"
		var resultFields []string
		if q.Command == model.One || q.Command == model.Many {
			if len(q.ResultSets) != 1 || len(q.ResultSets[0].Columns) == 0 {
				return nil, fmt.Errorf("%s: jOOQ requires one result set", q.Name)
			}
			var fields []string
			seen := map[string]bool{}
			for i, c := range q.ResultSets[0].Columns {
				typ, dataType, e := jooqType(c.Type)
				if e != nil {
					return nil, e
				}
				resultFields = append(resultFields, "field(name("+quoted(c.ResultName())+"), "+dataType+")")
				field := c.Name
				if embed := javaEmbeddingAt(q.ResultSets[0], i); embed != nil {
					if embed.Start != i {
						continue
					}
					field = embed.Field
					typ, e = tableName(embed.Table)
					if e != nil {
						return nil, e
					}
				}
				fn, e := name(field, false)
				if e != nil {
					return nil, e
				}
				if seen[fn] {
					return nil, fmt.Errorf("%s: Java field collision: %s", q.Name, fn)
				}
				seen[fn] = true
				fields = append(fields, typ+" "+fn)
			}
			if modelNames[row] {
				return nil, fmt.Errorf("jOOQ model name collision: %s", row)
			}
			modelNames[row] = true
			files = append(files, model.File{Name: row + ".java", Content: []byte(header + "public record " + row + "(" + strings.Join(fields, ", ") + ") {}\n")})
			ret = "Optional<" + row + ">"
			if q.Command == model.Many {
				ret = "List<" + row + ">"
			}
		} else if q.Command != model.Exec {
			return nil, fmt.Errorf("%s: jOOQ does not support %s", q.Name, q.Command)
		}
		r := jooqRenderer{query: q, aliases: map[string]string{}, parameters: map[string]string{}}
		var params []string
		seen := map[string]bool{"dsl": true, "stmt": true}
		fullSQL := jdbc.HasDeclarations(q) || jooqRequiresFullSQL(q)
		if fullSQL {
			seen["tech"] = true
		}
		for _, p := range q.Parameters {
			pn, e := name(p.Name, false)
			if e != nil {
				return nil, e
			}
			if seen[pn] {
				return nil, fmt.Errorf("%s: Java parameter collision: %s", q.Name, pn)
			}
			seen[pn] = true
			typ, _, e := jooqType(p.Type)
			if e != nil {
				return nil, e
			}
			params = append(params, typ+" "+pn)
			r.parameters[p.Name] = pn
		}
		parameterList := strings.Join(params, ", ")
		if len(params) > 3 {
			parameterList = "\n            " + strings.Join(params, ",\n            ") + "\n    "
		}
		fmt.Fprintf(&b, "\n    // %s\n    public %s %s(%s) {\n", model.QueryAnnotation(q), ret, method, parameterList)
		if fullSQL {
			text := jdbc.NamedSQL(q)
			sql, err := jooqDeclaredSQL(q, text)
			if err != nil {
				return nil, err
			}
			var names []string
			for _, p := range q.Parameters {
				n, _ := name(p.Name, false)
				names = append(names, n)
			}
			emitJooqDeclared(&b, q, names, sql, row)
			b.WriteString("    }\n")
			continue
		}
		if q.MultipleStatements {
			return nil, fmt.Errorf("%s: multi-statement queries require the jOOQ declared-query path; add an explicit DECLARE for one of the parameters, or use runtime: jdbc or ydb", q.Name)
		}
		isSelect := jooqIsSelect(q.Syntax.Root)
		for _, rel := range q.Syntax.Relations {
			tn, e := jooqTableConstant(rel.Table)
			if e != nil {
				return nil, e
			}
			alias := tn
			if isSelect && rel.Alias != rel.Table {
				alias, e = name(strings.ReplaceAll(rel.Alias, "/", "_"), false)
				if e != nil {
					return nil, e
				}
				if seen[alias] {
					for authored, generated := range r.aliases {
						if generated == alias {
							return nil, fmt.Errorf("%s: Java alias collision: %s (from %q and %q)", q.Name, alias, authored, rel.Alias)
						}
					}
					return nil, fmt.Errorf("%s: Java alias collision: %s (from %q)", q.Name, alias, rel.Alias)
				}
				seen[alias] = true
				fmt.Fprintf(&b, "        var %s = %s.as(%s);\n", alias, tn, quoted(rel.Alias))
			}
			r.aliases[rel.Alias] = alias
		}
		body := strings.ReplaceAll(r.statement(), "\n", "\n        ")
		if r.err != nil {
			return nil, fmt.Errorf("%s: %w", q.Name, r.err)
		}
		if pragmas := jooqNodes[*parser.Pragma_stmtContext](q.Syntax.Root); len(pragmas) != 0 {
			// Keep pragmas with the typed statement so YDB applies its settings.
			text := string([]rune(q.SQL)[pragmas[0].GetStart().GetStart() : pragmas[len(pragmas)-1].GetStop().GetStop()+1])
			fmt.Fprintf(&b, "        var stmt = %s;\n\n", body)
			if q.Command == model.Exec {
				fmt.Fprintf(&b, "        dsl.query(\"{0};\\n{1}\", sql(%s), stmt).execute();\n", sqlLiteral(text))
			} else {
				fetch := "fetchOptional"
				if q.Command == model.Many {
					fetch = "fetch"
				}
				fmt.Fprintf(&b, "        return dsl.resultQuery(\"{0};\\n{1}\", sql(%s), stmt)\n                .coerce(%s)\n                .%s(%s);\n", sqlLiteral(text), strings.Join(resultFields, ", "), fetch, jooqRowMapper(q.ResultSets[0], row))
			}
		} else if q.Command == model.Exec {
			b.WriteString("        " + body + "\n                .execute();\n")
		} else {
			fetch := "fetchOptional"
			if q.Command == model.Many {
				fetch = "fetch"
			}
			if !isSelect {
				var fields []string
				table := r.aliases[q.Syntax.Relations[0].Alias]
				for _, c := range q.ResultSets[0].Columns {
					fields = append(fields, r.col(table, c.Name))
				}
				// The dialect uses DEFAULT, whose DML RETURNING execution calls
				// executeUpdate/getGeneratedKeys. YDB returns an ordinary result set.
				fmt.Fprintf(&b, "        var stmt = %s;\n\n        // YDB RETURNING produces a result set, not JDBC generated keys.\n        return dsl.resultQuery(\"{0}\", stmt)\n                .coerce(%s)\n                .%s(%s);\n", body, strings.Join(fields, ", "), fetch, jooqRowMapper(q.ResultSets[0], row))
			} else {
				fmt.Fprintf(&b, "        return %s\n                .coerce(%s)\n                .%s(%s);\n", body, strings.Join(resultFields, ", "), fetch, jooqRowMapper(q.ResultSets[0], row))
			}
		}
		b.WriteString("    }\n")
	}
	b.WriteString("}\n")
	files = append(files, model.File{Name: "Queries.java", Content: []byte(b.String())})
	for i := range files {
		files[i].Content = []byte(jooqImports(string(files[i].Content)))
	}
	return files, nil
}

func jooqRowMapper(result model.ResultSet, row string) string {
	if len(result.Embeds) == 0 {
		return "mapping(" + row + "::new)"
	}
	values := make([]string, len(result.Columns))
	for i, column := range result.Columns {
		typ, _, _ := jooqType(column.Type)
		values[i] = fmt.Sprintf("_record.get(%d, %s.class)", i, typ)
	}
	return "_record -> new " + row + "(" + strings.Join(javaRowValues(result, values), ", ") + ")"
}

func jooqRequiresFullSQL(q model.AnalyzedQuery) bool {
	if q.Syntax == nil {
		return false
	}
	for _, call := range jooqNodes[*parser.Unary_casual_subexprContext](q.Syntax.Root) {
		atom, suffix := call.Atom_expr(), call.Unary_subexpr_suffix()
		if atom == nil || suffix == nil || len(suffix.AllInvoke_expr()) == 0 {
			continue
		}
		if atom.Bind_parameter() != nil || atom.NAMESPACE() != nil && atom.GetText() != "Yson::ConvertToStringList" {
			return true
		}
	}
	for _, named := range jooqNodes[*parser.Named_nodes_stmtContext](q.Syntax.Root) {
		if named.Select_unparenthesized_stmt() != nil {
			return true
		}
		if named.Expr() != nil && len(jooqNodes[*parser.Select_subexprContext](named.Expr())) != 0 {
			return true
		}
	}
	for _, selectBinding := range q.Syntax.Selects {
		for _, relation := range selectBinding.Relations {
			if relation.Table == "$derived" {
				return true
			}
		}
	}
	return false
}

type jooqRenderer struct {
	query               model.AnalyzedQuery
	aliases, parameters map[string]string
	err                 error
}

func (r *jooqRenderer) fail(n antlr.Tree) string {
	if r.err == nil {
		text := "missing syntax"
		if p, ok := n.(antlr.ParseTree); ok {
			text = p.GetText()
		}
		r.err = fmt.Errorf("unsupported jOOQ syntax %q", text)
	}
	return ""
}
func jooqNodes[T antlr.Tree](root antlr.Tree) []T {
	var out []T
	if root == nil {
		return out
	}
	if n, ok := root.(T); ok {
		return append(out, n)
	}
	for _, c := range root.GetChildren() {
		out = append(out, jooqNodes[T](c)...)
	}
	return out
}
func jooqID(s string) string { return strings.Trim(s, "`") }
func (r *jooqRenderer) col(table, col string) string {
	c, e := jooqConstant(col)
	if e != nil {
		r.err = e
	}
	return table + "." + c
}
func (r *jooqRenderer) expr(n antlr.Tree) string {
	if n == nil {
		return r.fail(n)
	}
	if node, ok := n.(*parser.Unary_subexprContext); ok {
		if c, ok := r.query.Syntax.Columns[node.GetStart().GetTokenIndex()]; ok && node.Unary_casual_subexpr() != nil {
			return r.col(r.aliases[c.Alias], c.Column.Name)
		}
		if casual := node.Unary_casual_subexpr(); casual != nil && casual.Id_expr() != nil && casual.Unary_subexpr_suffix().GetText() == "" {
			identifier := casual.Id_expr().GetText()
			if strings.HasPrefix(identifier, "`") {
				identifier = strings.ReplaceAll(identifier[1:len(identifier)-1], "``", "`")
			}
			ordering := false
			for parent := node.GetParent(); parent != nil; parent = parent.GetParent() {
				if _, ok := parent.(*parser.Order_by_clauseContext); ok {
					ordering = true
				}
				if core, ok := parent.(*parser.Select_coreContext); ok {
					if ordering {
						for _, column := range r.query.Syntax.Selects[core.GetStart().GetTokenIndex()].Columns {
							if identifier == column.ResultName() {
								_, dataType, err := jooqType(column.Type)
								if err != nil {
									r.err = err
								}
								return "field(name(" + quoted(column.ResultName()) + "), " + dataType + ")"
							}
						}
					}
					break
				}
			}
		}
	}
	switch node := n.(type) {
	case *parser.Cast_exprContext:
		if node.Type_name_or_bind() == nil || !strings.EqualFold(node.Type_name_or_bind().GetText(), "Bool") {
			return r.fail(n)
		}
		return r.expr(node.Expr()) + ".cast(YdbTypes.BOOL)"
	case *parser.Bind_parameterContext:
		key := strings.TrimPrefix(node.GetText(), "$")
		pn, ok := r.parameters[key]
		if !ok {
			return r.fail(n)
		}
		for _, p := range r.query.Parameters {
			if p.Name == key {
				_, dt, e := jooqType(p.Type)
				if e != nil {
					r.err = e
				}
				return "val(" + pn + ", " + dt + ")"
			}
		}
	case *parser.Literal_valueContext:
		text := node.GetText()
		if strings.HasSuffix(text, "u") && (strings.HasPrefix(text, "\"") || strings.HasPrefix(text, "'")) {
			content := text[1 : len(text)-2]
			if strings.ContainsAny(content, "\\\n\r") || strings.Contains(content, string(text[0])) {
				return r.fail(n)
			}
			return "inline(" + quoted(content) + ", YdbTypes.UTF8)"
		}
		if text != "" && strings.Trim(text, "0123456789") == "" {
			value, err := strconv.ParseInt(text, 10, 64)
			if err != nil {
				return r.fail(n)
			}
			text = strconv.FormatInt(value, 10)
			if value > 2147483647 {
				text += "L"
			}
			return "inline(" + text + ")"
		}
		return r.fail(n)
	case *parser.Unary_casual_subexprContext:
		if suffix := node.Unary_subexpr_suffix(); suffix != nil && len(suffix.AllInvoke_expr()) > 0 {
			if len(suffix.AllInvoke_expr()) != 1 {
				return r.fail(n)
			}
			inv := suffix.Invoke_expr(0)
			function := ""
			if node.Id_expr() != nil {
				function = node.Id_expr().GetText()
			} else if node.Atom_expr() != nil {
				function = node.Atom_expr().GetText()
			}
			var args []string
			if inv.Named_expr_list() != nil {
				for _, x := range inv.Named_expr_list().AllNamed_expr() {
					args = append(args, r.expr(x.Expr()))
				}
			}
			switch strings.ToLower(function) {
			case "count_if":
				return jooqCall("function", append([]string{"systemName(\"COUNT_IF\")", "YdbTypes.UINT64"}, args...))
			case "count":
				if inv.GetText() == "(*)" {
					return "count().coerce(YdbTypes.UINT64)"
				}
			case "yson::converttostringlist", "toset":
				return jooqCall("function", append([]string{"systemName(" + quoted(function) + ")", "SQLDataType.OTHER"}, args...))
			case "setisdisjoint":
				return jooqCall("condition", []string{jooqCall("function", append([]string{"systemName(" + quoted(function) + ")", "YdbTypes.BOOL"}, args...))})
			}
			return r.fail(n)
		}
	}
	var children []antlr.Tree
	for _, child := range n.GetChildren() {
		if p, ok := child.(antlr.ParseTree); ok && p.GetText() != "" {
			children = append(children, child)
		}
	}
	if len(children) == 1 {
		return r.expr(children[0])
	}
	if len(children) == 2 {
		if strings.EqualFold(children[0].(antlr.ParseTree).GetText(), "NOT") {
			return r.expr(children[1]) + ".not()"
		}
		if cond, ok := children[1].(*parser.Cond_exprContext); ok {
			if cond.IN() != nil {
				selects := jooqNodes[*parser.Select_coreContext](cond.In_expr())
				if len(selects) == 1 {
					return r.inSubquery(children[0], cond, selects[0])
				}
			}
			if cond.NULL() != nil || cond.ISNULL() != nil || cond.NOTNULL() != nil {
				method := "isNull"
				if cond.NOT() != nil || cond.NOTNULL() != nil {
					method = "isNotNull"
				}
				return r.expr(children[0]) + "." + method + "()"
			}
			parts := cond.GetChildren()
			if len(parts) == 2 {
				op := parts[0].(antlr.ParseTree).GetText()
				if method := jooqOperator(op); method != "" {
					return r.expr(children[0]) + "." + method + "(" + r.expr(parts[1]) + ")"
				}
			}
		}
	}
	if len(children) == 3 {
		if children[0].(antlr.ParseTree).GetText() == "(" && children[2].(antlr.ParseTree).GetText() == ")" {
			return r.expr(children[1])
		}
		op := children[1].(antlr.ParseTree).GetText()
		if method := jooqOperator(op); method != "" {
			return r.expr(children[0]) + "." + method + "(" + r.expr(children[2]) + ")"
		}
	}
	return r.fail(n)
}
func jooqOperator(op string) string {
	return map[string]string{"=": "eq", "==": "eq", "!=": "ne", "<>": "ne", "<": "lt", ">": "gt", "<=": "le", ">=": "ge", "AND": "and", "OR": "or", "||": "concat"}[strings.ToUpper(op)]
}

func jooqIsSelect(root antlr.Tree) bool {
	for _, stmt := range jooqNodes[*parser.Sql_stmtContext](root) {
		if stmt.Sql_stmt_core().Select_stmt() != nil {
			return true
		}
	}
	return false
}

func (r *jooqRenderer) inSubquery(left antlr.Tree, condition *parser.Cond_exprContext, core *parser.Select_coreContext) string {
	scope := r.query.Syntax.Selects[core.GetStart().GetTokenIndex()]
	if len(scope.Columns) == 1 && scope.Columns[0].Type.UnwrapOptional().Kind == "Tuple" {
		r.err = fmt.Errorf("tuple IN subqueries require explicit DECLARE parameters or runtime: jdbc or ydb; the jOOQ DSL cannot preserve YQL's single tuple projection")
		return ""
	}
	inner := *r
	inner.aliases = map[string]string{}
	for _, relation := range scope.Relations {
		table, err := jooqTableConstant(relation.Table)
		if err != nil {
			r.err = err
			return ""
		}
		if relation.Alias != relation.Table {
			table += ".as(" + quoted(relation.Alias) + ")"
		}
		inner.aliases[relation.Alias] = table
	}
	selectSQL := inner.selectQuery(core)
	if inner.err != nil {
		r.err = inner.err
		return ""
	}
	operator := "IN"
	if condition.NOT() != nil {
		operator = "NOT IN"
	}
	// YQL permits comparable operands with different scalar types; Java's
	// Field<T>.in(Select<Record1<T>>) would reject those typed query parts.
	return jooqCall("condition", []string{quoted("{0} " + operator + " ({1})"), r.expr(left), selectSQL})
}

func (r *jooqRenderer) statement() string {
	root := r.query.Syntax.Root
	for _, stmt := range jooqNodes[*parser.Sql_stmtContext](root) {
		core := stmt.Sql_stmt_core()
		if core.Pragma_stmt() != nil {
			continue
		}
		var source parser.IInto_values_sourceContext
		if into := core.Into_table_stmt(); into != nil {
			source = into.Into_values_source()
		} else if update := core.Update_stmt(); update != nil {
			source = update.Into_values_source()
		} else if del := core.Delete_stmt(); del != nil {
			source = del.Into_values_source()
		}
		if source != nil && len(jooqNodes[*parser.Select_coreContext](source)) > 0 {
			r.err = fmt.Errorf("SELECT-backed DML is unsupported by the jOOQ DSL; use runtime: jdbc or ydb")
			return ""
		}
		if selectStmt := core.Select_stmt(); selectStmt != nil {
			selects := jooqNodes[*parser.Select_coreContext](selectStmt)
			if len(selects) != 1 || len(jooqNodes[*parser.Union_opContext](selectStmt)) > 0 {
				return r.fail(selectStmt)
			}
			return r.selectQuery(selects[0])
		}
		if core.Declare_stmt() == nil && core.Into_table_stmt() == nil && core.Update_stmt() == nil && core.Delete_stmt() == nil {
			return r.fail(core)
		}
	}

	rel := r.query.Syntax.Relations
	if len(rel) != 1 {
		return r.fail(root)
	}
	table := r.aliases[rel[0].Alias]
	var body string
	if nodes := jooqNodes[*parser.Into_table_stmtContext](root); len(nodes) == 1 {
		stmt := nodes[0]
		op := strings.ToUpper(stmt.GetChild(0).(antlr.ParseTree).GetText())
		method := map[string]string{"INSERT": "insertInto", "UPSERT": "upsertInto"}[op]
		if method == "" {
			return r.fail(stmt)
		}
		src := stmt.Into_values_source()
		if src == nil || src.Pure_column_list() == nil || src.Values_source() == nil || src.Values_source().Values_stmt() == nil {
			return r.fail(stmt)
		}
		var cols []string
		for _, id := range src.Pure_column_list().AllAn_id() {
			cols = append(cols, r.col(table, jooqID(id.GetText())))
		}
		body = jooqCall("dsl."+method, append([]string{table}, cols...))
		for _, row := range src.Values_source().Values_stmt().Values_source_row_list().AllValues_source_row() {
			var values []string
			for _, x := range jooqNodes[*parser.ExprContext](row.Expr_list()) {
				values = append(values, r.expr(x))
			}
			body += "\n        " + strings.ReplaceAll(jooqCall(".values", values), "\n", "\n        ")
		}
	} else if nodes := jooqNodes[*parser.Update_stmtContext](root); len(nodes) == 1 {
		stmt := nodes[0]
		body = "dsl.update(" + table + ")"
		for _, set := range jooqNodes[*parser.Set_clauseContext](stmt.Set_clause_choice()) {
			body += "\n        .set(" + r.col(table, jooqID(set.Set_target().Column_name().An_id().GetText())) + ", " + r.expr(set.Expr()) + ")"
		}
		if stmt.Expr() != nil {
			body += "\n        " + strings.ReplaceAll(jooqCall(".where", []string{r.expr(stmt.Expr())}), "\n", "\n        ")
		}
	} else if nodes := jooqNodes[*parser.Delete_stmtContext](root); len(nodes) == 1 {
		body = "dsl.deleteFrom(" + table + ")"
		if nodes[0].Expr() != nil {
			body += "\n        " + strings.ReplaceAll(jooqCall(".where", []string{r.expr(nodes[0].Expr())}), "\n", "\n        ")
		}
	} else {
		return r.fail(root)
	}
	if r.query.Command == model.One || r.query.Command == model.Many {
		var cols []string
		for _, c := range r.query.ResultSets[0].Columns {
			_, dataType, err := jooqType(c.Type)
			if err != nil {
				r.err = err
			}
			cols = append(cols, "field(name("+quoted(c.Name)+"), "+dataType+")")
		}
		body += "\n        " + strings.ReplaceAll(jooqCall(".returningResult", cols), "\n", "\n        ")
	}
	return body
}

// Keep VIEW as a table query part so the dialect still maps the base table.
func (r *jooqRenderer) tableSource(source parser.IFlatten_sourceContext, rel model.TableBinding) string {
	named := source.Named_single_source()
	ref := named.Hinted_single_source().Single_source().Table_ref()
	if ref == nil || ref.Table_key() == nil {
		return r.fail(source)
	}
	view := ref.Table_key().View_name()
	if view == nil {
		return r.aliases[rel.Alias]
	}
	table, err := jooqTableConstant(rel.Table)
	if err != nil {
		r.err = err
		return ""
	}
	index := view.GetText()
	if strings.HasPrefix(index, "`") {
		index = strings.ReplaceAll(index[1:len(index)-1], "``", "`")
	}
	result := "table(\"{0} VIEW {1}\", " + table + ", name(" + quoted(index) + "))"
	if rel.Alias != rel.Table {
		result += ".as(" + quoted(rel.Alias) + ")"
	}
	return result
}

func (r *jooqRenderer) selectQuery(core *parser.Select_coreContext) string {
	var cols []string
	for _, c := range core.AllResult_column() {
		if c.Expr() == nil {
			return r.fail(c)
		}
		expr := r.expr(c.Expr())
		if c.An_id_or_type() != nil {
			expr += ".as(" + quoted(jooqID(c.An_id_or_type().GetText())) + ")"
		}
		cols = append(cols, expr)
	}
	method := "select"
	if core.Opt_set_quantifier() != nil {
		s := strings.ToUpper(core.Opt_set_quantifier().GetText())
		if s == "DISTINCT" {
			method = "selectDistinct"
		} else if s != "" && s != "ALL" {
			return r.fail(core)
		}
	}
	body := jooqCall("dsl."+method, cols)
	rel := r.query.Syntax.Selects[core.GetStart().GetTokenIndex()].Relations
	if len(rel) > 0 {
		if len(core.AllJoin_source()) != 1 {
			return r.fail(core)
		}
		join := core.Join_source(0)
		body += "\n        .from(" + r.tableSource(join.Flatten_source(0), rel[0]) + ")"
		for i, op := range join.AllJoin_op() {
			m := map[string]string{"JOIN": "join", "INNERJOIN": "join", "LEFTJOIN": "leftJoin", "LEFTOUTERJOIN": "leftJoin"}[strings.ToUpper(op.GetText())]
			if m == "" {
				return r.fail(op)
			}
			if i >= len(join.AllJoin_constraint()) {
				return r.fail(join)
			}
			body += "\n        ." + m + "(" + r.tableSource(join.Flatten_source(i+1), rel[i+1]) + ")\n        .on(" + r.expr(join.Join_constraint(i).Expr()) + ")"
		}
	}
	// WHERE and HAVING are direct expressions of the SELECT core.
	for i, c := range core.GetChildren() {
		if term, ok := c.(antlr.TerminalNode); ok {
			switch strings.ToUpper(term.GetText()) {
			case "WHERE":
				body += "\n        " + strings.ReplaceAll(jooqCall(".where", []string{r.expr(core.GetChild(i + 1))}), "\n", "\n        ")
			case "HAVING":
				return r.fail(core)
			}
		}
	}
	if group := core.Group_by_clause(); group != nil {
		var items []string
		for _, x := range jooqNodes[*parser.Named_exprContext](group) {
			items = append(items, r.expr(x.Expr()))
		}
		body += "\n        .groupBy(" + strings.Join(items, ", ") + ")"
	}
	var ordering []string
	for _, order := range jooqNodes[*parser.Sort_specificationContext](core.Ext_order_by_clause()) {
		expr := r.expr(order.Expr())
		if strings.HasSuffix(strings.ToUpper(order.GetText()), "DESC") {
			expr += ".desc()"
		}
		ordering = append(ordering, expr)
	}
	if len(ordering) != 0 {
		body += "\n        " + strings.ReplaceAll(jooqCall(".orderBy", ordering), "\n", "\n        ")
	}
	for parent := core.GetParent(); parent != nil; parent = parent.GetParent() {
		limit, ok := parent.(*parser.Select_kind_partialContext)
		if !ok {
			continue
		}
		if limit.LIMIT() == nil {
			break
		}
		xs := limit.AllExpr()
		if len(xs) != 1 {
			return r.fail(limit)
		}
		body += "\n        .limit(" + r.expr(xs[0]) + ")"
		break
	}
	return body
}

// Import carriers without rewriting query literals or generated identifiers.
func jooqImports(code string) string {
	carriers := map[string]string{}
	for _, qualified := range []string{"org.jooq.types.UByte", "org.jooq.types.UShort", "org.jooq.types.UInteger", "org.jooq.types.ULong", "org.jooq.JSON", "org.jooq.JSONB", "java.time.Instant", "java.time.LocalDateTime", "java.time.LocalDate", "java.time.Duration", "java.util.UUID"} {
		carriers[qualified] = qualified[strings.LastIndex(qualified, ".")+1:]
	}
	var body strings.Builder
	used := map[string]bool{}
	for i := 0; i < len(code); {
		start := i
		switch {
		case code[i] == '"':
			i++
			for i < len(code) {
				c := code[i]
				i++
				if c == '\\' && i < len(code) {
					i++
				} else if c == '"' {
					break
				}
			}
		case strings.HasPrefix(code[i:], "//"):
			for i < len(code) && code[i] != '\n' {
				i++
			}
		case code[i] >= 'a' && code[i] <= 'z':
			for i < len(code) && (code[i] >= 'a' && code[i] <= 'z' || code[i] >= 'A' && code[i] <= 'Z' || code[i] >= '0' && code[i] <= '9' || code[i] == '.' || code[i] == '_') {
				i++
			}
			token := code[start:i]
			if simple, ok := carriers[token]; ok {
				body.WriteString(simple)
				used[token] = true
				continue
			}
		default:
			i++
		}
		body.WriteString(code[start:i])
	}
	code = body.String()
	if len(used) == 0 {
		return code
	}
	var imports []string
	for qualified := range used {
		imports = append(imports, "import "+qualified+";")
	}
	sort.Strings(imports)
	index := strings.Index(code, ";\n\n") + 3
	return code[:index] + strings.Join(imports, "\n") + "\n\n" + code[index:]
}

func jooqCall(function string, args []string) string {
	joined := strings.Join(args, ", ")
	if len(function)+len(joined) < 100 && !strings.Contains(joined, "\n") {
		return function + "(" + joined + ")"
	}
	for i, arg := range args {
		args[i] = "    " + strings.ReplaceAll(arg, "\n", "\n    ")
	}
	return function + "(\n" + strings.Join(args, ",\n") + "\n)"
}
