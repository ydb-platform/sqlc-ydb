// jooqType uses the YDB dialect's native carriers and bindings.
func jooqType(t model.Type) (string, string, error) {
	kinds := map[string]string{"Bool": "Boolean", "Int8": "Byte", "Int16": "Short", "Int32": "Integer", "Int64": "Long", "Uint8": "org.jooq.types.UByte", "Uint16": "org.jooq.types.UShort", "Uint32": "org.jooq.types.UInteger", "Uint64": "org.jooq.types.ULong", "Float": "Float", "Double": "Double", "Utf8": "String", "String": "byte[]", "Json": "org.jooq.JSON", "JsonDocument": "org.jooq.JSONB", "Timestamp": "java.time.Instant", "Date": "java.time.LocalDate", "Datetime": "java.time.LocalDateTime", "Interval": "java.time.Duration", "Uuid": "java.util.UUID"}
	k := t.UnwrapOptional().Kind
	typ, ok := kinds[k]
	if !ok {
		return "", "", fmt.Errorf("jOOQ does not support type %s", t.String())
	}
	return typ, "YdbTypes." + strings.ToUpper(k), nil
}
func jooqConstant(s string) (string, error) {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' || r == '.' })
	for i, part := range parts {
		n, err := name(part, true)
		if err != nil {
			return "", err
		}
		parts[i] = strings.ToUpper(n)
	}
	result := strings.Join(parts, "_")
	if !identifier(result) {
		return "", fmt.Errorf("invalid jOOQ identifier %q", s)
	}
	return result, nil
}

func generateJooq(a *model.AnalysisResult, o Options) ([]model.File, error) {
	header := "// Code generated by sqlc-ydb. DO NOT EDIT.\npackage " + o.Package + ";\n\n"
	files := []model.File{}
	var tables strings.Builder
	tables.WriteString(header + "import org.jooq.Record;\nimport org.jooq.Table;\nimport org.jooq.TableField;\nimport org.jooq.impl.TableImpl;\nimport tech.ydb.jooq.YdbTypes;\n\nimport static org.jooq.impl.DSL.name;\n\npublic final class Tables {\n    private Tables() {}\n")
	tableNames := map[string]bool{}
	for _, t := range a.Catalog.Tables {
		cn, err := name(t.Name, true)
		if err != nil {
			return nil, err
		}
		cn += "Table"
		constant, err := jooqConstant(t.Name)
		if err != nil {
			return nil, err
		}
		if tableNames[cn] || tableNames[constant] {
			return nil, fmt.Errorf("jOOQ table name collision: %s", t.Name)
		}
		tableNames[cn] = true
		tableNames[constant] = true
		fmt.Fprintf(&tables, "\n    public static final %s %s = new %s(%s, null);\n\n    public static final class %s extends TableImpl<Record> {\n", cn, constant, cn, quoted(t.Name), cn)
		fields := map[string]bool{}
		for _, c := range t.Columns {
			fn, err := jooqConstant(c.Name)
			if err != nil {
				return nil, err
			}
			if fields[fn] {
				return nil, fmt.Errorf("jOOQ field collision in %s: %s", t.Name, fn)
			}
			fields[fn] = true
			typ, dt, err := jooqType(c.Type)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&tables, "        public final TableField<Record, %s> %s = createField(name(%s), %s.nullable(%t), this);\n", typ, fn, quoted(c.Name), dt, c.Type.IsOptional())
		}
		fmt.Fprintf(&tables, "\n        private %s(String name, Table<Record> aliased) {\n            super(name(name), null, aliased);\n        }\n\n        @Override\n        public %s as(String alias) {\n            return new %s(alias, this);\n        }\n    }\n", cn, cn, cn)
	}
	tables.WriteString("}\n")
	files = append(files, model.File{Name: "Tables.java", Content: []byte(tables.String())})
	var b strings.Builder
	b.WriteString(header + "import java.util.List;\nimport java.util.Objects;\nimport java.util.Optional;\n\nimport org.jooq.impl.SQLDataType;\nimport tech.ydb.jooq.YdbDSLContext;\nimport tech.ydb.jooq.YdbTypes;\n\nimport static org.jooq.impl.DSL.*;\nimport static org.jooq.Records.mapping;\nimport static " + o.Package + ".Tables.*;\n\npublic final class Queries {\n    private final YdbDSLContext dsl;\n\n    public Queries(YdbDSLContext dsl) {\n        this.dsl = Objects.requireNonNull(dsl);\n    }\n")
	methods := map[string]bool{}
	for _, q := range a.Queries {
		if q.Syntax == nil {
			return nil, fmt.Errorf("%s: jOOQ requires analyzed YQL syntax", q.Name)
		}
		method, err := name(q.Name, false)
		if err != nil {
			return nil, err
		}
		if methods[method] {
			return nil, fmt.Errorf("Java method name collision: %s", method)
		}
		methods[method] = true
		row, err := name(q.Name+"Row", true)
		if err != nil {
			return nil, err
		}
		ret := "void"
		if q.Command == model.One || q.Command == model.Many {
			if len(q.ResultSets) != 1 || len(q.ResultSets[0].Columns) == 0 {
				return nil, fmt.Errorf("%s: jOOQ requires one result set", q.Name)
			}
			var fields []string
			seen := map[string]bool{}
			for _, c := range q.ResultSets[0].Columns {
				fn, e := name(c.Name, false)
				if e != nil {
					return nil, e
				}
				if seen[fn] {
					return nil, fmt.Errorf("%s: Java field collision: %s", q.Name, fn)
				}
				seen[fn] = true
				typ, _, e := jooqType(c.Type)
				if e != nil {
					return nil, e
				}
				fields = append(fields, typ+" "+fn)
			}
			files = append(files, model.File{Name: row + ".java", Content: []byte(header + "public record " + row + "(" + strings.Join(fields, ", ") + ") {}\n")})
			ret = "Optional<" + row + ">"
			if q.Command == model.Many {
				ret = "List<" + row + ">"
			}
		} else if q.Command != model.Exec {
			return nil, fmt.Errorf("%s: jOOQ does not support %s", q.Name, q.Command)
		}
		r := jooqRenderer{query: q, aliases: map[string]string{}, parameters: map[string]string{}}
		var params []string
		seen := map[string]bool{"dsl": true, "stmt": true}
		for _, p := range q.Parameters {
			pn, e := name(p.Name, false)
			if e != nil {
				return nil, e
			}
			if seen[pn] {
				return nil, fmt.Errorf("%s: Java parameter collision: %s", q.Name, pn)
			}
			seen[pn] = true
			typ, _, e := jooqType(p.Type)
			if e != nil {
				return nil, e
			}
			params = append(params, typ+" "+pn)
			r.parameters[p.Name] = pn
		}
		parameterList := strings.Join(params, ", ")
		if len(params) > 3 {
			parameterList = "\n            " + strings.Join(params, ",\n            ") + "\n    "
		}
		fmt.Fprintf(&b, "\n    // %s\n    public %s %s(%s) {\n", model.QueryAnnotation(q), ret, method, parameterList)
		for _, rel := range q.Syntax.Relations {
			tn, e := jooqConstant(rel.Table)
			if e != nil {
				return nil, e
			}
			alias := tn
			if rel.Alias != rel.Table {
				alias, e = name(rel.Alias, false)
				if e != nil {
					return nil, e
				}
				if seen[alias] {
					return nil, fmt.Errorf("%s: Java alias collision: %s", q.Name, alias)
				}
				seen[alias] = true
				fmt.Fprintf(&b, "        var %s = %s.as(%s);\n", alias, tn, quoted(rel.Alias))
			}
			r.aliases[rel.Alias] = alias
		}
		body := strings.ReplaceAll(r.statement(), "\n", "\n        ")
		if r.err != nil {
			return nil, fmt.Errorf("%s: %w", q.Name, r.err)
		}
		if q.Command == model.Exec {
			b.WriteString("        " + body + "\n                .execute();\n")
		} else {
			fetch := "fetchOptional"
			if q.Command == model.Many {
				fetch = "fetch"
			}
			if len(jooqNodes[*parser.Select_coreContext](q.Syntax.Root)) == 0 {
				var fields []string
				table := r.aliases[q.Syntax.Relations[0].Alias]
				for _, c := range q.ResultSets[0].Columns {
					fields = append(fields, r.col(table, c.Name))
				}
				// The dialect uses DEFAULT, whose DML RETURNING execution calls
				// executeUpdate/getGeneratedKeys. YDB returns an ordinary result set.
				fmt.Fprintf(&b, "        var stmt = %s;\n\n        // YDB RETURNING produces a result set, not JDBC generated keys.\n        return dsl.resultQuery(\"{0}\", stmt)\n                .coerce(%s)\n                .%s(mapping(%s::new));\n", body, strings.Join(fields, ", "), fetch, row)
			} else {
				fmt.Fprintf(&b, "        return %s\n                .%s(mapping(%s::new));\n", body, fetch, row)
			}
		}
		b.WriteString("    }\n")
	}
	b.WriteString("}\n")
	files = append(files, model.File{Name: "Queries.java", Content: []byte(b.String())})
	for i := range files {
		files[i].Content = []byte(jooqImports(string(files[i].Content)))
	}
	return files, nil
}

type jooqRenderer struct {
	query               model.AnalyzedQuery
	aliases, parameters map[string]string
	err                 error
}

func (r *jooqRenderer) fail(n antlr.Tree) string {
	if r.err == nil {
		text := "missing syntax"
		if p, ok := n.(antlr.ParseTree); ok {
			text = p.GetText()
		}
		r.err = fmt.Errorf("unsupported jOOQ syntax %q", text)
	}
	return ""
}
func jooqNodes[T antlr.Tree](root antlr.Tree) []T {
	var out []T
	if root == nil {
		return out
	}
	if n, ok := root.(T); ok {
		return append(out, n)
	}
	for _, c := range root.GetChildren() {
		out = append(out, jooqNodes[T](c)...)
	}
	return out
}
func jooqID(s string) string { return strings.Trim(s, "`") }
func (r *jooqRenderer) col(table, col string) string {
	c, e := jooqConstant(col)
	if e != nil {
		r.err = e
	}
	return table + "." + c
}
func (r *jooqRenderer) expr(n antlr.Tree) string {
	if n == nil {
		return r.fail(n)
	}
	if node, ok := n.(*parser.Unary_subexprContext); ok {
		if c, ok := r.query.Syntax.Columns[node.GetStart().GetTokenIndex()]; ok && node.Unary_casual_subexpr() != nil {
			return r.col(r.aliases[c.Alias], c.Column.Name)
		}
	}
	switch node := n.(type) {
	case *parser.Bind_parameterContext:
		key := strings.TrimPrefix(node.GetText(), "$")
		pn, ok := r.parameters[key]
		if !ok {
			return r.fail(n)
		}
		for _, p := range r.query.Parameters {
			if p.Name == key {
				_, dt, e := jooqType(p.Type)
				if e != nil {
					r.err = e
				}
				return "val(" + pn + ", " + dt + ")"
			}
		}
	case *parser.Literal_valueContext:
		text := node.GetText()
		if strings.HasSuffix(text, "u") && (strings.HasPrefix(text, "\"") || strings.HasPrefix(text, "'")) {
			content := text[1 : len(text)-2]
			if strings.ContainsAny(content, "\\\n\r") || strings.Contains(content, string(text[0])) {
				return r.fail(n)
			}
			return "inline(" + quoted(content) + ", YdbTypes.UTF8)"
		}
		if text != "" && strings.Trim(text, "0123456789") == "" {
			value, err := strconv.ParseInt(text, 10, 64)
			if err != nil {
				return r.fail(n)
			}
			text = strconv.FormatInt(value, 10)
			if value > 2147483647 {
				text += "L"
			}
			return "inline(" + text + ")"
		}
		return r.fail(n)
	case *parser.Unary_casual_subexprContext:
		if suffix := node.Unary_subexpr_suffix(); suffix != nil && len(suffix.AllInvoke_expr()) > 0 {
			if len(suffix.AllInvoke_expr()) != 1 {
				return r.fail(n)
			}
			inv := suffix.Invoke_expr(0)
			function := ""
			if node.Id_expr() != nil {
				function = node.Id_expr().GetText()
			} else if node.Atom_expr() != nil {
				function = node.Atom_expr().GetText()
			}
			var args []string
			if inv.Named_expr_list() != nil {
				for _, x := range inv.Named_expr_list().AllNamed_expr() {
					args = append(args, r.expr(x.Expr()))
				}
			}
			switch strings.ToLower(function) {
			case "count":
				if inv.GetText() == "(*)" {
					return "count().coerce(YdbTypes.UINT64)"
				}
			case "yson::converttostringlist", "toset":
				return jooqCall("function", append([]string{"systemName(" + quoted(function) + ")", "SQLDataType.OTHER"}, args...))
			case "setisdisjoint":
				return jooqCall("condition", []string{jooqCall("function", append([]string{"systemName(" + quoted(function) + ")", "YdbTypes.BOOL"}, args...))})
			}
			return r.fail(n)
		}
	}
	var children []antlr.Tree
	for _, child := range n.GetChildren() {
		if p, ok := child.(antlr.ParseTree); ok && p.GetText() != "" {
			children = append(children, child)
		}
	}
	if len(children) == 1 {
		return r.expr(children[0])
	}
	if len(children) == 2 {
		if strings.EqualFold(children[0].(antlr.ParseTree).GetText(), "NOT") {
			return r.expr(children[1]) + ".not()"
		}
		if cond, ok := children[1].(*parser.Cond_exprContext); ok {
			parts := cond.GetChildren()
			if len(parts) == 2 {
				op := parts[0].(antlr.ParseTree).GetText()
				if method := jooqOperator(op); method != "" {
					return r.expr(children[0]) + "." + method + "(" + r.expr(parts[1]) + ")"
				}
			}
		}
	}
	if len(children) == 3 {
		if children[0].(antlr.ParseTree).GetText() == "(" && children[2].(antlr.ParseTree).GetText() == ")" {
			return r.expr(children[1])
		}
		op := children[1].(antlr.ParseTree).GetText()
		if method := jooqOperator(op); method != "" {
			return r.expr(children[0]) + "." + method + "(" + r.expr(children[2]) + ")"
		}
	}
	return r.fail(n)
}
func jooqOperator(op string) string {
	return map[string]string{"=": "eq", "==": "eq", "!=": "ne", "<>": "ne", "<": "lt", ">": "gt", "<=": "le", ">=": "ge", "AND": "and", "OR": "or", "||": "concat"}[strings.ToUpper(op)]
}

func (r *jooqRenderer) statement() string {
	root := r.query.Syntax.Root
	for _, stmt := range jooqNodes[*parser.Sql_stmtContext](root) {
		core := stmt.Sql_stmt_core()
		if core.Declare_stmt() == nil && core.Select_stmt() == nil && core.Into_table_stmt() == nil && core.Update_stmt() == nil && core.Delete_stmt() == nil {
			return r.fail(core)
		}
	}
	selects := jooqNodes[*parser.Select_coreContext](root)
	if len(selects) > 0 {
		if len(selects) != 1 || len(jooqNodes[*parser.Union_opContext](root)) > 0 {
			return r.fail(root)
		}
		return r.selectQuery(selects[0])
	}
	rel := r.query.Syntax.Relations
	if len(rel) != 1 {
		return r.fail(root)
	}
	table := r.aliases[rel[0].Alias]
	var body string
	if nodes := jooqNodes[*parser.Into_table_stmtContext](root); len(nodes) == 1 {
		stmt := nodes[0]
		op := strings.ToUpper(stmt.GetChild(0).(antlr.ParseTree).GetText())
		method := map[string]string{"INSERT": "insertInto", "UPSERT": "upsertInto"}[op]
		if method == "" {
			return r.fail(stmt)
		}
		src := stmt.Into_values_source()
		if src == nil || src.Pure_column_list() == nil || src.Values_source() == nil || src.Values_source().Values_stmt() == nil {
			return r.fail(stmt)
		}
		var cols []string
		for _, id := range src.Pure_column_list().AllAn_id() {
			cols = append(cols, r.col(table, jooqID(id.GetText())))
		}
		body = jooqCall("dsl."+method, append([]string{table}, cols...))
		for _, row := range src.Values_source().Values_stmt().Values_source_row_list().AllValues_source_row() {
			var values []string
			for _, x := range jooqNodes[*parser.ExprContext](row.Expr_list()) {
				values = append(values, r.expr(x))
			}
			body += "\n        " + strings.ReplaceAll(jooqCall(".values", values), "\n", "\n        ")
		}
	} else if nodes := jooqNodes[*parser.Update_stmtContext](root); len(nodes) == 1 {
		stmt := nodes[0]
		body = "dsl.update(" + table + ")"
		for _, set := range jooqNodes[*parser.Set_clauseContext](stmt.Set_clause_choice()) {
			body += "\n        .set(" + r.col(table, jooqID(set.Set_target().Column_name().An_id().GetText())) + ", " + r.expr(set.Expr()) + ")"
		}
		if stmt.Expr() != nil {
			body += "\n        .where(" + r.expr(stmt.Expr()) + ")"
		}
	} else if nodes := jooqNodes[*parser.Delete_stmtContext](root); len(nodes) == 1 {
		body = "dsl.deleteFrom(" + table + ")"
		if nodes[0].Expr() != nil {
			body += "\n        .where(" + r.expr(nodes[0].Expr()) + ")"
		}
	} else {
		return r.fail(root)
	}
	if r.query.Command == model.One || r.query.Command == model.Many {
		var cols []string
		for _, c := range r.query.ResultSets[0].Columns {
			_, dataType, err := jooqType(c.Type)
			if err != nil {
				r.err = err
			}
			cols = append(cols, "field(name("+quoted(c.Name)+"), "+dataType+")")
		}
		body += "\n        " + strings.ReplaceAll(jooqCall(".returningResult", cols), "\n", "\n        ")
	}
	return body
}
func (r *jooqRenderer) selectQuery(core *parser.Select_coreContext) string {
	var cols []string
	for _, c := range core.AllResult_column() {
		if c.Expr() == nil {
			return r.fail(c)
		}
		expr := r.expr(c.Expr())
		if c.An_id_or_type() != nil {
			expr += ".as(" + quoted(jooqID(c.An_id_or_type().GetText())) + ")"
		}
		cols = append(cols, expr)
	}
	method := "select"
	if core.Opt_set_quantifier() != nil {
		s := strings.ToUpper(core.Opt_set_quantifier().GetText())
		if s == "DISTINCT" {
			method = "selectDistinct"
		} else if s != "" && s != "ALL" {
			return r.fail(core)
		}
	}
	body := jooqCall("dsl."+method, cols)
	rel := r.query.Syntax.Relations
	if len(rel) > 0 {
		if len(core.AllJoin_source()) != 1 {
			return r.fail(core)
		}
		join := core.Join_source(0)
		body += "\n        .from(" + r.aliases[rel[0].Alias] + ")"
		for i, op := range join.AllJoin_op() {
			m := map[string]string{"JOIN": "join", "INNERJOIN": "join", "LEFTJOIN": "leftJoin", "LEFTOUTERJOIN": "leftJoin"}[strings.ToUpper(op.GetText())]
			if m == "" {
				return r.fail(op)
			}
			if i >= len(join.AllJoin_constraint()) {
				return r.fail(join)
			}
			body += "\n        ." + m + "(" + r.aliases[rel[i+1].Alias] + ")\n        .on(" + r.expr(join.Join_constraint(i).Expr()) + ")"
		}
	}
	// WHERE and HAVING are direct expressions of the SELECT core.
	for i, c := range core.GetChildren() {
		if term, ok := c.(antlr.TerminalNode); ok {
			switch strings.ToUpper(term.GetText()) {
			case "WHERE":
				body += "\n        " + strings.ReplaceAll(jooqCall(".where", []string{r.expr(core.GetChild(i + 1))}), "\n", "\n        ")
			case "HAVING":
				return r.fail(core)
			}
		}
	}
	if group := core.Group_by_clause(); group != nil {
		var items []string
		for _, x := range jooqNodes[*parser.Named_exprContext](group) {
			items = append(items, r.expr(x.Expr()))
		}
		body += "\n        .groupBy(" + strings.Join(items, ", ") + ")"
	}
	for _, order := range jooqNodes[*parser.Sort_specificationContext](r.query.Syntax.Root) {
		expr := r.expr(order.Expr())
		if strings.HasSuffix(strings.ToUpper(order.GetText()), "DESC") {
			expr += ".desc()"
		}
		body += "\n        .orderBy(" + expr + ")"
	}
	for _, limit := range jooqNodes[*parser.Select_kind_partialContext](r.query.Syntax.Root) {
		if limit.LIMIT() == nil {
			continue
		}
		xs := limit.AllExpr()
		if len(xs) != 1 {
			return r.fail(limit)
		}
		body += "\n        .limit(" + r.expr(xs[0]) + ")"
	}
	return body
}

// Import carriers without rewriting query literals or generated identifiers.
func jooqImports(code string) string {
	carriers := map[string]string{}
	for _, qualified := range []string{"org.jooq.types.UByte", "org.jooq.types.UShort", "org.jooq.types.UInteger", "org.jooq.types.ULong", "org.jooq.JSON", "org.jooq.JSONB", "java.time.Instant", "java.time.LocalDateTime", "java.time.LocalDate", "java.time.Duration", "java.util.UUID"} {
		carriers[qualified] = qualified[strings.LastIndex(qualified, ".")+1:]
	}
	var body strings.Builder
	used := map[string]bool{}
	for i := 0; i < len(code); {
		start := i
		switch {
		case code[i] == '"':
			i++
			for i < len(code) {
				c := code[i]
				i++
				if c == '\\' && i < len(code) {
					i++
				} else if c == '"' {
					break
				}
			}
		case strings.HasPrefix(code[i:], "//"):
			for i < len(code) && code[i] != '\n' {
				i++
			}
		case code[i] >= 'a' && code[i] <= 'z':
			for i < len(code) && (code[i] >= 'a' && code[i] <= 'z' || code[i] >= 'A' && code[i] <= 'Z' || code[i] >= '0' && code[i] <= '9' || code[i] == '.' || code[i] == '_') {
				i++
			}
			token := code[start:i]
			if simple, ok := carriers[token]; ok {
				body.WriteString(simple)
				used[token] = true
				continue
			}
		default:
			i++
		}
		body.WriteString(code[start:i])
	}
	code = body.String()
	if len(used) == 0 {
		return code
	}
	var imports []string
	for qualified := range used {
		imports = append(imports, "import "+qualified+";")
	}
	sort.Strings(imports)
	index := strings.Index(code, ";\n\n") + 3
	return code[:index] + strings.Join(imports, "\n") + "\n\n" + code[index:]
}

func jooqCall(function string, args []string) string {
	joined := strings.Join(args, ", ")
	if len(function)+len(joined) < 100 && !strings.Contains(joined, "\n") {
		return function + "(" + joined + ")"
	}
	for i, arg := range args {
		args[i] = "    " + strings.ReplaceAll(arg, "\n", "\n    ")
	}
	return function + "(\n" + strings.Join(args, ",\n") + "\n)"
}
