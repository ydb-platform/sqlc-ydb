// Package golang renders the resolved YQL model as ordinary Go source.
package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/ydb-platform/sqlc-engine-ydb/internal/model"
)

type Options struct {
	Package         string
	Runtime         string // ydb or database/sql
	EmitJSONTags    bool
	EmitInterface   bool
	EmitEmptySlices bool
}

func Generate(in *model.AnalysisResult, o Options) ([]model.File, error) {
	if in == nil {
		return nil, fmt.Errorf("analysis result is nil")
	}
	if len(in.Diagnostics) != 0 {
		return nil, fmt.Errorf("cannot generate with diagnostics: %s", in.Diagnostics[0])
	}
	if o.Package == "" {
		o.Package = "db"
	}
	if !ident(o.Package) || o.Package == "_" {
		return nil, fmt.Errorf("invalid Go package %q", o.Package)
	}
	if o.Runtime == "" {
		o.Runtime = "ydb"
	}
	if o.Runtime != "ydb" && o.Runtime != "database/sql" {
		return nil, fmt.Errorf("unsupported Go runtime %q", o.Runtime)
	}
	if err := validate(in, o); err != nil {
		return nil, err
	}
	files := []model.File{{Name: "models.go", Content: models(in, o)}, {Name: "db.go", Content: db(o)}}
	needsDecimalValidation := false
	for _, q := range in.Queries {
		for _, p := range q.Parameters {
			needsDecimalValidation = needsDecimalValidation || hasKind(p.Type, "decimal")
		}
	}
	if needsDecimalValidation {
		files = append(files, model.File{Name: "decimal.go", Content: []byte("// Code generated by sqlc-ydb. DO NOT EDIT.\npackage " + o.Package + `
import ("fmt"; "github.com/ydb-platform/ydb-go-sdk/v3/types")
func validateDecimalParameter(name string, value types.Decimal, precision, scale uint32) error {
 if value.Precision != precision || value.Scale != scale {
  return fmt.Errorf("Decimal parameter %s expects Decimal(%d,%d), got Decimal(%d,%d)", name, precision, scale, value.Precision, value.Scale)
 }
 return nil
}
`)})
	}
	bySource := map[string][]model.AnalyzedQuery{}
	for _, q := range in.Queries {
		n := sourceName(q)
		bySource[n] = append(bySource[n], q)
	}
	names := make([]string, 0, len(bySource))
	for n := range bySource {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		files = append(files, model.File{Name: outputName(n), Content: queryFile(n, bySource[n], o)})
	}
	for i := range files {
		formatted, err := format.Source(files[i].Content)
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", files[i].Name, err)
		}
		files[i].Content = formatted
	}
	return files, nil
}

func validate(in *model.AnalysisResult, o Options) error {
	seen := map[string]bool{}
	outputs := map[string]string{}
	for _, q := range in.Queries {
		if !ident(q.Name) || seen[q.Name] {
			return fmt.Errorf("invalid or duplicate query name %q", q.Name)
		}
		if o.Runtime == "database/sql" && q.Name == "WithTx" {
			return fmt.Errorf("query name %q conflicts with generated Queries.WithTx", q.Name)
		}
		seen[q.Name] = true
		source := sourceName(q)
		out := outputName(source)
		if previous, ok := outputs[out]; ok && previous != source {
			return fmt.Errorf("multiple query sources map to generated file %q", out)
		}
		outputs[out] = source
		if q.Command != model.One && q.Command != model.Many && q.Command != model.Exec && q.Command != model.ExecRows {
			return fmt.Errorf("%s: unsupported command %q", q.Name, q.Command)
		}
		if q.Command == model.ExecRows {
			return fmt.Errorf("%s: :execrows is unavailable for %s", q.Name, o.Runtime)
		}
		if (q.Command == model.One || q.Command == model.Many) && (len(q.ResultSets) != 1 || len(q.ResultSets[0].Columns) == 0) {
			return fmt.Errorf("%s: %s requires one non-empty result set", q.Name, q.Command)
		}
		field := map[string]bool{}
		for _, p := range q.Parameters {
			if !ident(goName(p.Name)) || field[goName(p.Name)] {
				return fmt.Errorf("%s: colliding parameter %q", q.Name, p.Name)
			}
			field[goName(p.Name)] = true
			if _, err := goType(p.Type); err != nil {
				return fmt.Errorf("%s parameter %s: %w", q.Name, p.Name, err)
			}
			if hasKind(p.Type, "list") {
				if o.Runtime == "database/sql" {
					return fmt.Errorf("%s parameter %s: List parameters are unsupported by database/sql", q.Name, p.Name)
				}
				if err := validateNativeListParameter(p.Type); err != nil {
					return fmt.Errorf("%s parameter %s: %w", q.Name, p.Name, err)
				}
			}
			if err := validateDecimal(p.Type); err != nil {
				return fmt.Errorf("%s parameter %s: %w", q.Name, p.Name, err)
			}
		}
		for _, rs := range q.ResultSets {
			field := map[string]bool{}
			for _, c := range rs.Columns {
				n := goName(c.Name)
				if !ident(n) || field[n] {
					return fmt.Errorf("%s: colliding result column %q", q.Name, c.Name)
				}
				field[n] = true
				if _, err := goType(c.Type); err != nil {
					return fmt.Errorf("%s column %s: %w", q.Name, c.Name, err)
				}
				if o.Runtime == "database/sql" && hasKind(c.Type, "list") {
					return fmt.Errorf("%s column %s: List results are unsupported by database/sql", q.Name, c.Name)
				}
				if optionalList(c.Type) {
					return fmt.Errorf("%s column %s: Optional<List> results are unsupported", q.Name, c.Name)
				}
				if err := validateDecimal(c.Type); err != nil {
					return fmt.Errorf("%s column %s: %w", q.Name, c.Name, err)
				}
			}
		}
	}
	return nil
}

func validateNativeListParameter(t model.Type) error {
	if t.IsOptional() {
		return fmt.Errorf("Optional<List> parameters are unsupported by the native Go runtime")
	}
	if !strings.EqualFold(t.Kind, "List") || t.Elem == nil {
		return fmt.Errorf("List lacks element")
	}
	e := *t.Elem
	if e.IsOptional() {
		if e.Elem == nil || e.Elem.IsOptional() || hasKind(*e.Elem, "list") {
			return fmt.Errorf("List element must be a scalar or Optional<scalar>")
		}
		if extendedListTemporal(e) {
			return fmt.Errorf("List<%s> parameters are unsupported by the native Go runtime: SDK list builder has no %s method", e.Elem.Kind, e.Elem.Kind)
		}
		return validateDecimal(*e.Elem)
	}
	if hasKind(e, "list") {
		return fmt.Errorf("nested List parameters are unsupported by the native Go runtime")
	}
	if extendedListTemporal(e) {
		return fmt.Errorf("List<%s> parameters are unsupported by the native Go runtime: SDK list builder has no %s method", e.Kind, e.Kind)
	}
	return validateDecimal(e)
}

func extendedListTemporal(t model.Type) bool {
	if t.IsOptional() {
		if t.Elem == nil {
			return false
		}
		t = *t.Elem
	}
	switch strings.ToLower(t.Kind) {
	case "date32", "datetime64", "timestamp64", "interval64":
		return true
	default:
		return false
	}
}

func validateDecimal(t model.Type) error {
	if t.IsOptional() {
		if t.Elem == nil {
			return fmt.Errorf("Optional lacks element")
		}
		if t.Elem.IsOptional() && hasKind(t, "decimal") {
			return fmt.Errorf("nested Optional<Decimal> is unsupported")
		}
		return validateDecimal(*t.Elem)
	}
	if strings.EqualFold(t.Kind, "Decimal") && (t.Precision <= 0 || t.Precision > 35 || t.Scale < 0 || t.Scale > t.Precision) {
		return fmt.Errorf("Decimal requires precision 1..35 and scale 0..precision")
	}
	if t.Elem != nil {
		return validateDecimal(*t.Elem)
	}
	return nil
}

func optionalList(t model.Type) bool {
	return t.IsOptional() && t.Elem != nil && hasKind(*t.Elem, "list")
}

func sourceName(q model.AnalyzedQuery) string {
	if q.Source.File == "" {
		return "query.sql"
	}
	return q.Source.File
}

func goType(t model.Type) (string, error) {
	if t.IsOptional() {
		if t.Elem == nil {
			return "", fmt.Errorf("Optional lacks element")
		}
		e, err := goType(*t.Elem)
		return "*" + e, err
	}
	switch strings.ToLower(t.Kind) {
	case "bool":
		return "bool", nil
	case "int8":
		return "int8", nil
	case "int16":
		return "int16", nil
	case "int32":
		return "int32", nil
	case "int64":
		return "int64", nil
	case "uint8":
		return "uint8", nil
	case "uint16":
		return "uint16", nil
	case "uint32":
		return "uint32", nil
	case "uint64":
		return "uint64", nil
	case "float":
		return "float32", nil
	case "double":
		return "float64", nil
	case "utf8", "json", "jsondocument":
		return "string", nil
	case "string", "yson":
		return "[]byte", nil
	case "timestamp", "timestamp64", "date", "date32", "datetime", "datetime64":
		return "time.Time", nil
	case "interval", "interval64":
		return "time.Duration", nil
	case "decimal":
		return "types.Decimal", nil
	case "uuid":
		return "uuid.UUID", nil
	case "list":
		if t.Elem == nil {
			return "", fmt.Errorf("List lacks element")
		}
		e, err := goType(*t.Elem)
		return "[]" + e, err
	default:
		return "", fmt.Errorf("unsupported YQL type %q", t.Kind)
	}
}

func models(in *model.AnalysisResult, o Options) []byte {
	var b bytes.Buffer
	var imports typeImports
	for _, q := range in.Queries {
		if q.Command == model.One || q.Command == model.Many {
			r := q.ResultSets[0]
			b.WriteString("type " + q.Name + "Row struct {\n")
			for _, c := range r.Columns {
				typ, _ := goType(c.Type)
				imports.add(c.Type)
				b.WriteString(goName(c.Name) + " " + typ)
				if o.EmitJSONTags {
					b.WriteString(" `json:" + strconv.Quote(c.Name) + "`")
				}
				b.WriteString("\n")
			}
			b.WriteString("}\n\n")
		}
		if len(q.Parameters) > 1 {
			b.WriteString("type " + q.Name + "Params struct {\n")
			for _, p := range q.Parameters {
				typ, _ := goType(p.Type)
				imports.add(p.Type)
				b.WriteString(goName(p.Name) + " " + typ)
				if o.EmitJSONTags {
					b.WriteString(" `json:" + strconv.Quote(p.Name) + "`")
				}
				b.WriteString("\n")
			}
			b.WriteString("}\n\n")
		}
	}
	if o.EmitInterface {
		b.WriteString("type Querier interface {\n")
		for _, q := range in.Queries {
			for _, p := range q.Parameters {
				imports.add(p.Type)
			}
			sig := methodArgs(q, o)
			ret := "error"
			if q.Command == model.One {
				ret = "(" + q.Name + "Row, error)"
			}
			if q.Command == model.Many {
				ret = "([]" + q.Name + "Row, error)"
			}
			b.WriteString(q.Name + "(ctx context.Context" + sig + ") " + ret + "\n")
		}
		b.WriteString("}\n")
	}
	packages := []string{}
	if imports.time {
		packages = append(packages, "\"time\"")
	}
	if imports.decimal {
		packages = append(packages, "\"github.com/ydb-platform/ydb-go-sdk/v3/types\"")
	}
	if imports.uuid {
		packages = append(packages, "\"github.com/google/uuid\"")
	}
	if o.EmitInterface {
		packages = append(packages, "\"context\"")
		if o.Runtime == "ydb" {
			packages = append(packages, "\"github.com/ydb-platform/ydb-go-sdk/v3/query\"")
		}
	}
	var head strings.Builder
	head.WriteString("// Code generated by sqlc-ydb. DO NOT EDIT.\npackage " + o.Package + "\n\n")
	if len(packages) == 1 {
		head.WriteString("import " + packages[0] + "\n\n")
	} else if len(packages) > 1 {
		head.WriteString("import (" + strings.Join(packages, ";") + ")\n\n")
	}
	return append([]byte(head.String()), b.Bytes()...)
}

type typeImports struct{ time, decimal, uuid bool }

func (i *typeImports) add(t model.Type) {
	switch strings.ToLower(t.Kind) {
	case "timestamp", "timestamp64", "date", "date32", "datetime", "datetime64", "interval", "interval64":
		i.time = true
	case "decimal":
		i.decimal = true
	case "uuid":
		i.uuid = true
	}
	if t.Elem != nil {
		i.add(*t.Elem)
	}
}

func hasKind(t model.Type, kind string) bool {
	if strings.EqualFold(t.Kind, kind) {
		return true
	}
	return t.Elem != nil && hasKind(*t.Elem, kind)
}

func db(o Options) []byte {
	if o.Runtime == "database/sql" {
		return []byte(`// Code generated by sqlc-ydb. DO NOT EDIT.
package ` + o.Package + `
import ("context"; "database/sql")
type DBTX interface { ExecContext(context.Context,string,...any)(sql.Result,error); QueryContext(context.Context,string,...any)(*sql.Rows,error); QueryRowContext(context.Context,string,...any)*sql.Row }
type Queries struct { db DBTX }
func New(db DBTX) *Queries { return &Queries{db:db} }
func (q *Queries) WithTx(tx *sql.Tx) *Queries { return &Queries{db:tx} }
`)
	}
	return []byte(`// Code generated by sqlc-ydb. DO NOT EDIT.
package ` + o.Package + `
import ("context"; "github.com/ydb-platform/ydb-go-sdk/v3/query")
type DBTX interface { Exec(context.Context,string,...query.ExecuteOption) error; QueryResultSet(context.Context,string,...query.ExecuteOption)(query.ClosableResultSet,error); QueryRow(context.Context,string,...query.ExecuteOption)(query.Row,error) }
type Queries struct { db DBTX }
func New(db DBTX) *Queries { return &Queries{db:db} }
`)
}

func queryFile(source string, qs []model.AnalyzedQuery, o Options) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by sqlc-ydb. DO NOT EDIT.\n// source: " + filepath.Base(source) + "\npackage " + o.Package + "\n\n")
	needsJSON, needsSQLNamed, needsTypes, needsUUID, needsYDB := false, false, false, false, false
	var parameterImports typeImports
	for _, q := range qs {
		for _, p := range q.Parameters {
			if len(q.Parameters) == 1 {
				parameterImports.add(p.Type)
			}
			kind := strings.ToLower(p.Type.UnwrapOptional().Kind)
			if kind == "json" || kind == "jsondocument" {
				needsJSON = true
			} else if kind != "decimal" && kind != "uuid" {
				needsSQLNamed = true
			}
			needsUUID = needsUUID || (len(q.Parameters) == 1 && hasKind(p.Type, "uuid"))
			needsTypes = needsTypes ||
				(o.Runtime == "database/sql" && (kind == "uuid" || kind == "decimal")) ||
				(o.Runtime == "ydb" && (hasKind(p.Type, "list") || (len(q.Parameters) == 1 && hasKind(p.Type, "decimal"))))
			needsYDB = needsYDB || o.Runtime == "ydb"
		}
	}
	if o.Runtime == "database/sql" {
		b.WriteString("import (\n\"context\"\n")
		if parameterImports.time {
			b.WriteString("\"time\"\n")
		}
		if needsSQLNamed {
			b.WriteString("\"database/sql\"\n")
		}
		if needsJSON || needsTypes {
			b.WriteString("\"github.com/ydb-platform/ydb-go-sdk/v3/table\"\n")
			b.WriteString("\"github.com/ydb-platform/ydb-go-sdk/v3/types\"\n")
		}
		if needsUUID {
			b.WriteString("\"github.com/google/uuid\"\n")
		}
	} else {
		b.WriteString("import (\n\"context\"\n")
		if parameterImports.time {
			b.WriteString("\"time\"\n")
		}
		if needsYDB {
			b.WriteString("ydb \"github.com/ydb-platform/ydb-go-sdk/v3\"\n")
		}
		b.WriteString("\"github.com/ydb-platform/ydb-go-sdk/v3/query\"\n")
		if needsTypes {
			b.WriteString("\"github.com/ydb-platform/ydb-go-sdk/v3/types\"\n")
		}
		if needsUUID {
			b.WriteString("\"github.com/google/uuid\"\n")
		}
	}
	b.WriteString(")\n\n")

	for _, q := range qs {
		writeQuery(&b, q, o)
	}
	return b.Bytes()
}

func writeQuery(b *bytes.Buffer, q model.AnalyzedQuery, o Options) {
	c := "const " + queryConstName(q.Name) + " = " + sqlLiteral(q.SQL) + "\n\n"
	b.WriteString(c)
	ret := "error"
	if q.Command == model.One {
		ret = "(" + q.Name + "Row, error)"
	}
	if q.Command == model.Many {
		ret = "([]" + q.Name + "Row, error)"
	}
	sig := methodArgs(q, o)
	b.WriteString("func (q *Queries) " + q.Name + "(ctx context.Context" + sig + ") " + ret + " {\n")
	if o.Runtime == "database/sql" {
		writeSQL(b, q, o)
	} else {
		writeYDB(b, q, o)
	}
	b.WriteString("}\n\n")
}

func sqlLiteral(sql string) string {
	if !strings.ContainsAny(sql, "`\r\x00\ufeff") && utf8.ValidString(sql) {
		return "`" + sql + "`"
	}
	// Keep each SQL line intact when raw strings cannot represent its contents.
	// SplitAfter retains line endings, including the final newline if present.
	lines := strings.SplitAfter(sql, "\n")
	if lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	for i, line := range lines {
		lines[i] = strconv.Quote(line)
	}
	return strings.Join(lines, " +\n")
}

func methodArgs(q model.AnalyzedQuery, o Options) string {
	args := ""
	if len(q.Parameters) > 1 {
		args = ", arg " + q.Name + "Params"
	} else if len(q.Parameters) == 1 {
		t, _ := goType(q.Parameters[0].Type)
		args = ", arg " + t
	}
	if o.Runtime == "ydb" {
		args += ", opts ...query.ExecuteOption"
	}
	return args
}
func varRef(q model.AnalyzedQuery, p model.Parameter) string {
	if len(q.Parameters) > 1 {
		return "arg." + goName(p.Name)
	}
	return "arg"
}
func sqlArgs(q model.AnalyzedQuery) string {
	x := make([]string, len(q.Parameters))
	for i, p := range q.Parameters {
		value := varRef(q, p)
		typeValue := p.Type.UnwrapOptional()
		switch strings.ToLower(typeValue.Kind) {
		case "json":
			constructor := "types.JSONValue"
			if p.Type.IsOptional() {
				constructor = "types.NullableJSONValue"
			}
			x[i] = "table.ValueParam(" + strconv.Quote("$"+p.Name) + ", " + constructor + "(" + value + "))"
		case "jsondocument":
			constructor := "types.JSONDocumentValue"
			if p.Type.IsOptional() {
				constructor = "types.NullableJSONDocumentValue"
			}
			x[i] = "table.ValueParam(" + strconv.Quote("$"+p.Name) + ", " + constructor + "(" + value + "))"
		case "decimal":
			precision, scale := decimalArgs(typeValue)
			decimalValue := "types.Decimal{Bytes: " + value + ".Bytes, Precision: " + precision + ", Scale: " + scale + "}"
			if p.Type.IsOptional() {
				x[i] = "table.ValueParam(" + strconv.Quote("$"+p.Name) + ", func() types.Value { if " + value + " == nil { return types.NullableDecimalValue(nil, " + precision + ", " + scale + ") }; return types.NullableDecimalValue(&" + value + ".Bytes, " + precision + ", " + scale + ") }())"
			} else {
				x[i] = "table.ValueParam(" + strconv.Quote("$"+p.Name) + ", types.DecimalValue(&" + decimalValue + "))"
			}
		case "uuid":
			constructor := "types.UuidValue"
			if p.Type.IsOptional() {
				constructor = "types.NullableUUIDTypedValue"
			}
			x[i] = "table.ValueParam(" + strconv.Quote("$"+p.Name) + ", " + constructor + "(" + value + "))"
		default:
			x[i] = "sql.Named(" + strconv.Quote(p.Name) + ", " + value + ")"
		}
	}
	if len(x) == 0 {
		return ""
	}
	return ", " + strings.Join(x, ", ")
}
func writeSQL(b *bytes.Buffer, q model.AnalyzedQuery, o Options) {
	writeDecimalValidations(b, q, o)
	a := sqlArgs(q)
	switch q.Command {
	case model.Exec:
		b.WriteString("_, err := q.db.ExecContext(ctx, " + queryConstName(q.Name) + a + ")\nreturn err\n")
	case model.One:
		b.WriteString("var row " + q.Name + "Row\nerr := q.db.QueryRowContext(ctx, " + queryConstName(q.Name) + a + ").Scan(" + scan(q.ResultSets[0]) + ")\nreturn row, err\n")
	case model.Many:
		init := "[]" + q.Name + "Row(nil)"
		if o.EmitEmptySlices {
			init = "make([]" + q.Name + "Row, 0)"
		}
		b.WriteString("rows, err := q.db.QueryContext(ctx, " + queryConstName(q.Name) + a + ")\nif err != nil { return " + init + ", err }; defer rows.Close()\nitems := " + init + "\nfor rows.Next() { var row " + q.Name + "Row\nif err := rows.Scan(" + scan(q.ResultSets[0]) + "); err != nil { return nil, err }; items = append(items, row) }\nreturn items, rows.Err()\n")
	}
}
func writeYDB(b *bytes.Buffer, q model.AnalyzedQuery, o Options) {
	opt := "opts..."
	if len(q.Parameters) != 0 {
		writeDecimalValidations(b, q, o)
		b.WriteString("parameters := ydb.ParamsBuilder()\n")
		for i, p := range q.Parameters {
			writeYDBParameter(b, p, varRef(q, p), i)
		}
		// Execute options are applied in order by the SDK. Put generated parameters
		// last so callers can supply execution settings but cannot replace bindings
		// represented by this method's typed arguments.
		b.WriteString("callOptions := append([]query.ExecuteOption(nil), opts...)\n")
		b.WriteString("callOptions = append(callOptions, query.WithParameters(parameters.Build()))\n")
		opt = "callOptions..."
	}
	if q.Command == model.Exec {
		b.WriteString("return q.db.Exec(ctx, " + queryConstName(q.Name) + ", " + opt + ")\n")
		return
	}
	if q.Command == model.One {
		b.WriteString("result, err := q.db.QueryRow(ctx, " + queryConstName(q.Name) + ", " + opt + ")\nif err != nil { return " + q.Name + "Row{}, err }; var row " + q.Name + "Row\nif err := result.Scan(" + scan(q.ResultSets[0]) + "); err != nil { return " + q.Name + "Row{}, err }; return row, nil\n")
		return
	}
	init := "[]" + q.Name + "Row(nil)"
	if o.EmitEmptySlices {
		init = "make([]" + q.Name + "Row, 0)"
	}
	b.WriteString("result, err := q.db.QueryResultSet(ctx, " + queryConstName(q.Name) + ", " + opt + ")\nif err != nil { return " + init + ", err }; defer result.Close(ctx)\nitems := " + init + "\nfor r, err := range result.Rows(ctx) { if err != nil { return nil, err }; var row " + q.Name + "Row; if err := r.Scan(" + scan(q.ResultSets[0]) + "); err != nil { return nil, err }; items = append(items, row) }\nreturn items, nil\n")
}

func writeDecimalValidations(b *bytes.Buffer, q model.AnalyzedQuery, o Options) {
	for i, p := range q.Parameters {
		value := varRef(q, p)
		failure := decimalValidationFailure(q, o)
		if strings.EqualFold(p.Type.UnwrapOptional().Kind, "Decimal") {
			precision, scale := decimalArgs(p.Type.UnwrapOptional())
			if p.Type.IsOptional() {
				b.WriteString("if " + value + " != nil { if err := validateDecimalParameter(" + strconv.Quote("$"+p.Name) + ", *" + value + ", " + precision + ", " + scale + "); err != nil { " + failure + " } }\n")
			} else {
				b.WriteString("if err := validateDecimalParameter(" + strconv.Quote("$"+p.Name) + ", " + value + ", " + precision + ", " + scale + "); err != nil { " + failure + " }\n")
			}
			continue
		}
		if !strings.EqualFold(p.Type.Kind, "List") || p.Type.Elem == nil || !strings.EqualFold(p.Type.Elem.UnwrapOptional().Kind, "Decimal") {
			continue
		}
		precision, scale := decimalArgs(p.Type.Elem.UnwrapOptional())
		item := fmt.Sprintf("decimalItem%d", i)
		b.WriteString("for _, " + item + " := range " + value + " { ")
		if p.Type.Elem.IsOptional() {
			b.WriteString("if " + item + " != nil { if err := validateDecimalParameter(" + strconv.Quote("$"+p.Name) + ", *" + item + ", " + precision + ", " + scale + "); err != nil { " + failure + " } } ")
		} else {
			b.WriteString("if err := validateDecimalParameter(" + strconv.Quote("$"+p.Name) + ", " + item + ", " + precision + ", " + scale + "); err != nil { " + failure + " } ")
		}
		b.WriteString("}\n")
	}
}

func decimalValidationFailure(q model.AnalyzedQuery, o Options) string {
	switch q.Command {
	case model.One:
		return "return " + q.Name + "Row{}, err"
	case model.Many:
		init := "[]" + q.Name + "Row(nil)"
		if o.EmitEmptySlices {
			init = "make([]" + q.Name + "Row, 0)"
		}
		return "return " + init + ", err"
	default:
		return "return err"
	}
}
func scan(rs model.ResultSet) string {
	x := make([]string, len(rs.Columns))
	for i, c := range rs.Columns {
		x[i] = "&row." + goName(c.Name)
	}
	return strings.Join(x, ", ")
}
func writeYDBParameter(b *bytes.Buffer, p model.Parameter, value string, index int) {
	if strings.EqualFold(p.Type.Kind, "List") {
		writeYDBListParameter(b, p, value, index)
		return
	}
	method := paramMethod(p.Type)
	name := strconv.Quote("$" + p.Name)
	if strings.EqualFold(p.Type.UnwrapOptional().Kind, "Decimal") {
		precision, scale := decimalArgs(p.Type.UnwrapOptional())
		if p.Type.IsOptional() {
			v := fmt.Sprintf("decimalValue%d", index)
			b.WriteString("var " + v + " *[16]byte\nif " + value + " != nil { " + v + " = &" + value + ".Bytes }\n")
			b.WriteString("parameters = parameters.Param(" + name + ").BeginOptional().Decimal(" + v + ", " + precision + ", " + scale + ").EndOptional()\n")
			return
		}
		b.WriteString("parameters = parameters.Param(" + name + ").Decimal(" + value + ".Bytes, " + precision + ", " + scale + ")\n")
		return
	}
	if p.Type.IsOptional() {
		b.WriteString("parameters = parameters.Param(" + name + ").BeginOptional()." + method + "(" + value + ").EndOptional()\n")
		return
	}
	b.WriteString("parameters = parameters.Param(" + name + ")." + method + "(" + value + ")\n")
}

func writeYDBListParameter(b *bytes.Buffer, p model.Parameter, value string, index int) {
	e := *p.Type.Elem
	name := strconv.Quote("$" + p.Name)
	item := fmt.Sprintf("listItem%d", index)
	if e.IsOptional() {
		inner := *e.Elem
		b.WriteString("if len(" + value + ") == 0 {\n")
		b.WriteString("parameters = parameters.Param(" + name + ").Any(types.ZeroValue(types.List(types.Optional(" + ydbTypeExpr(inner) + "))))\n")
		b.WriteString("} else {\nlist := parameters.Param(" + name + ").BeginList()\n")
		b.WriteString("for _, " + item + " := range " + value + " { list = list.AddItems(" + nullableValueExpr(inner, item) + ") }\n")
		b.WriteString("parameters = list.EndList()\n}\n")
		return
	}
	b.WriteString("if len(" + value + ") == 0 {\n")
	b.WriteString("parameters = parameters.Param(" + name + ").Any(types.ZeroValue(types.List(" + ydbTypeExpr(e) + ")))\n")
	b.WriteString("} else {\nlist := parameters.Param(" + name + ").BeginList()\n")
	b.WriteString("for _, " + item + " := range " + value + " { list = list.Add()." + paramMethod(e) + "(" + listValueArg(e, item) + ") }\n")
	b.WriteString("parameters = list.EndList()\n}\n")
}

func decimalArgs(t model.Type) (string, string) {
	return strconv.Itoa(t.Precision), strconv.Itoa(t.Scale)
}

func listValueArg(t model.Type, value string) string {
	if strings.EqualFold(t.Kind, "Decimal") {
		precision, scale := decimalArgs(t)
		return value + ".Bytes, " + precision + ", " + scale
	}
	return value
}

func nullableValueExpr(t model.Type, value string) string {
	if strings.EqualFold(t.Kind, "Decimal") {
		precision, scale := decimalArgs(t)
		return "func() types.Value { if " + value + " == nil { return types.NullableDecimalValue(nil, " + precision + ", " + scale + ") }; return types.NullableDecimalValue(&" + value + ".Bytes, " + precision + ", " + scale + ") }()"
	}
	if strings.EqualFold(t.Kind, "Uuid") {
		return "types.NullableUUIDTypedValue(" + value + ")"
	}
	if strings.EqualFold(t.Kind, "Yson") {
		return "types.NullableYSONValueFromBytes(" + value + ")"
	}
	switch strings.ToLower(t.Kind) {
	case "date":
		return "types.NullableDateValueFromTime(" + value + ")"
	case "datetime":
		return "types.NullableDatetimeValueFromTime(" + value + ")"
	case "timestamp":
		return "types.NullableTimestampValueFromTime(" + value + ")"
	case "interval":
		return "types.NullableIntervalValueFromDuration(" + value + ")"
	}
	return "types.Nullable" + paramMethod(t) + "Value(" + value + ")"
}

func ydbTypeExpr(t model.Type) string {
	if strings.EqualFold(t.Kind, "Decimal") {
		precision, scale := decimalArgs(t)
		return "types.DecimalType(" + precision + ", " + scale + ")"
	}
	if strings.EqualFold(t.Kind, "Uuid") {
		return "types.TypeUUID"
	}
	return "types.Type" + paramMethod(t)
}
func paramMethod(t model.Type) string {
	if t.IsOptional() {
		t = *t.Elem
	}
	switch strings.ToLower(t.Kind) {
	case "utf8":
		return "Text"
	case "json":
		return "JSON"
	case "jsondocument":
		return "JSONDocument"
	case "string":
		return "Bytes"
	case "yson":
		return "YSON"
	case "float":
		return "Float"
	case "double":
		return "Double"
	case "timestamp":
		return "Timestamp"
	case "date":
		return "Date"
	case "datetime":
		return "Datetime"
	case "interval":
		return "Interval"
	case "decimal":
		return "Decimal"
	case "uuid":
		return "Uuid"
	default:
		return goName(t.Kind)
	}
}
func outputName(s string) string {
	s = filepath.Base(s)
	s = strings.TrimSuffix(s, ".sql")
	return s + ".sql.go"
}
func queryConstName(name string) string { return "query" + name }
func goName(s string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		if strings.EqualFold(part, "id") {
			b.WriteString("ID")
			continue
		}
		for i, r := range part {
			if i == 0 {
				b.WriteRune(unicode.ToUpper(r))
			} else {
				b.WriteRune(r)
			}
		}
	}
	x := b.String()
	if x == "" {
		return "Value"
	}
	return x
}
func ident(s string) bool {
	if s == "" {
		return false
	}
	if goKeywords[s] {
		return false
	}
	for i, r := range s {
		if !(r == '_' || unicode.IsLetter(r) || (i > 0 && unicode.IsDigit(r))) {
			return false
		}
	}
	return true
}

