package dbsql

import (
	"bytes"
	"context"
	"strings"
	"text/template"

	"github.com/sqlc-dev/sqlc-engine-ydb/internal/codegen/pb"
)

// Generate produces database/sql style Go files from a plugin GenerateRequest.
func Generate(ctx context.Context, req *pb.GenerateRequest) (*pb.GenerateResponse, error) {
	opts, err := parseOptions(req.GetPluginOptions())
	if err != nil {
		return nil, err
	}
	pkg := opts.Package
	if pkg == "" {
		pkg = "db"
	}
	outDir := "."
	if s := req.GetSettings(); s != nil && s.GetCodegen() != nil {
		outDir = s.GetCodegen().GetOut()
	}
	if outDir == "" {
		outDir = "."
	}

	var files []*pb.File

	models, err := genModels(req.GetCatalog(), req.GetQueries(), pkg)
	if err != nil {
		return nil, err
	}
	files = append(files, &pb.File{Name: "models.go", Contents: models})

	db, err := genDB(pkg)
	if err != nil {
		return nil, err
	}
	files = append(files, &pb.File{Name: "db.go", Contents: db})

	byFilename := make(map[string][]*pb.Query)
	for _, q := range req.GetQueries() {
		fn := q.GetFilename()
		if fn == "" {
			fn = "query.sql"
		}
		if idx := strings.LastIndex(fn, "/"); idx >= 0 {
			fn = fn[idx+1:]
		}
		byFilename[fn] = append(byFilename[fn], q)
	}
	for fname, qs := range byFilename {
		outName := strings.TrimSuffix(fname, ".sql") + ".sql.go"
		if outName == fname {
			outName = "query.sql.go"
		}
		content, err := genQueryFile(req.GetCatalog(), pkg, fname, qs)
		if err != nil {
			return nil, err
		}
		files = append(files, &pb.File{Name: outName, Contents: content})
	}

	return &pb.GenerateResponse{Files: files}, nil
}

func genModels(cat *pb.Catalog, queries []*pb.Query, pkg string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sqlc. DO NOT EDIT.\n")
	buf.WriteString("package " + pkg + "\n\n")

	for _, schema := range cat.GetSchemas() {
		for _, tbl := range schema.GetTables() {
			name := tbl.GetRel().GetName()
			if name == "" {
				continue
			}
			structName := toGoStruct(name)
			buf.WriteString("type " + structName + " struct {\n")
			for _, col := range tbl.GetColumns() {
				yt := ydbTypeName(col)
				goType := goTypeForDB(yt, col.GetNotNull())
				fname := toGoField(col.GetName())
				buf.WriteString("\t" + fname + " " + goType + " `json:\"" + col.GetName() + "\"`\n")
			}
			buf.WriteString("}\n\n")
		}
	}

	hasCatalogTables := false
	for _, s := range cat.GetSchemas() {
		if len(s.GetTables()) > 0 {
			hasCatalogTables = true
			break
		}
	}
	if !hasCatalogTables {
		for _, q := range queries {
			cols := q.GetColumns()
			if len(cols) == 0 {
				continue
			}
			cmd := strings.ToLower(q.GetCmd())
			if cmd != ":one" && cmd != ":many" {
				continue
			}
			name := q.GetName() + "Row"
			buf.WriteString("type " + name + " struct {\n")
			for _, col := range cols {
				yt := ydbTypeName(col)
				goType := goTypeForDB(yt, col.GetNotNull())
				fname := toGoField(col.GetName())
				buf.WriteString("\t" + fname + " " + goType + " `json:\"" + col.GetName() + "\"`\n")
			}
			buf.WriteString("}\n\n")
		}
	}
	return buf.Bytes(), nil
}

func genDB(pkg string) ([]byte, error) {
	t := template.Must(template.New("db").Parse(dbTemplate))
	var buf bytes.Buffer
	if err := t.Execute(&buf, map[string]string{"Package": pkg}); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

const dbTemplate = `// Code generated by sqlc. DO NOT EDIT.
package {{.Package}}

import (
	"context"
	"database/sql"
)

type DBTX interface {
	ExecContext(context.Context, string, ...interface{}) (sql.Result, error)
	QueryContext(context.Context, string, ...interface{}) (*sql.Rows, error)
	QueryRowContext(context.Context, string, ...interface{}) *sql.Row
}

func New(db DBTX) *Queries {
	return &Queries{db: db}
}

type Queries struct {
	db DBTX
}
`

func genQueryFile(cat *pb.Catalog, pkg, sourceName string, queries []*pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sqlc. DO NOT EDIT.\n// source: " + sourceName + "\n\n")
	buf.WriteString("package " + pkg + "\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"database/sql\"\n\n")
	buf.WriteString("\t_ \"github.com/ydb-platform/ydb-go-sdk/v3\"\n")
	buf.WriteString("\t\"github.com/ydb-platform/ydb-go-sdk/v3/pkg/xerrors\"\n")
	buf.WriteString("\t\"github.com/ydb-platform/ydb-go-sdk/v3/retry\"\n")
	buf.WriteString(")\n\n")

	for i, q := range queries {
		block, err := genQuery(cat, pkg, q)
		if err != nil {
			return nil, err
		}
		buf.Write(block)
		if i < len(queries)-1 {
			buf.WriteString("\n")
		}
	}
	return buf.Bytes(), nil
}

func genQuery(cat *pb.Catalog, pkg string, q *pb.Query) ([]byte, error) {
	var buf bytes.Buffer
	name := q.GetName()
	cmd := strings.ToLower(q.GetCmd())
	text := q.GetText()

	constName := toGoConst(name)
	buf.WriteString("const " + constName + " = `" + text + "`\n\n")

	if len(q.GetParams()) > 0 {
		buf.WriteString("type " + name + "Params struct {\n")
		for _, p := range q.GetParams() {
			col := p.GetColumn()
			if col == nil {
				continue
			}
			yt := ydbTypeName(col)
			goType := goTypeForDB(yt, col.GetNotNull())
			fname := toGoField(col.GetName())
			buf.WriteString("\t" + fname + " " + goType + " `json:\"" + col.GetName() + "\"`\n")
		}
		buf.WriteString("}\n\n")
	}

	switch cmd {
	case ":one":
		buf.WriteString(genOne(cat, name, constName, q))
	case ":many":
		buf.WriteString(genMany(cat, name, constName, q))
	default:
		buf.WriteString(genExec(name, constName, q))
	}
	return buf.Bytes(), nil
}

func catalogHasTable(cat *pb.Catalog, tableName string) bool {
	if cat == nil || tableName == "" {
		return false
	}
	for _, s := range cat.GetSchemas() {
		for _, t := range s.GetTables() {
			if t.GetRel().GetName() == tableName {
				return true
			}
		}
	}
	return false
}

func genOne(cat *pb.Catalog, name, constName string, q *pb.Query) string {
	var b bytes.Buffer
	params := q.GetParams()
	cols := q.GetColumns()
	retType := "interface{}"
	if len(cols) > 0 {
		for _, c := range cols {
			if t := c.GetTable(); t != nil && t.GetName() != "" && catalogHasTable(cat, t.GetName()) {
				retType = toGoStruct(t.GetName())
				break
			}
		}
		if retType == "interface{}" {
			retType = name + "Row"
		}
	}

	sig := "ctx context.Context, id int64"
	args := ""
	if len(params) > 0 {
		sig = "ctx context.Context, arg " + name + "Params"
		args = namedArgList(params)
	}
	b.WriteString("func (q *Queries) " + name + "(" + sig + ") (*" + retType + ", error) {\n")
	b.WriteString("\ti, err := retry.RetryWithResult(ctx, func(ctx context.Context) (*" + retType + ", error) {\n")
	b.WriteString("\t\trow := q.db.QueryRowContext(ctx, " + constName + args + ")\n")
	b.WriteString("\t\tvar i " + retType + "\n")
	b.WriteString("\t\terr := row.Scan(" + scanTargets(cols) + ")\n")
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t}\n\n")
	b.WriteString("\t\treturn &i, nil\n")
	b.WriteString("\t}, retry.WithLabel(\"" + name + "\"))\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\treturn i, nil\n")
	b.WriteString("}\n")
	return b.String()
}

func genMany(cat *pb.Catalog, name, constName string, q *pb.Query) string {
	var b bytes.Buffer
	params := q.GetParams()
	cols := q.GetColumns()
	rowType := "interface{}"
	if len(cols) > 0 {
		for _, c := range cols {
			if t := c.GetTable(); t != nil && t.GetName() != "" && catalogHasTable(cat, t.GetName()) {
				rowType = toGoStruct(t.GetName())
				break
			}
		}
		if rowType == "interface{}" {
			rowType = name + "Row"
		}
	}
	sig := "ctx context.Context"
	args := ""
	if len(params) > 0 {
		sig = "ctx context.Context, arg " + name + "Params"
		args = namedArgList(params)
	}
	b.WriteString("func (q *Queries) " + name + "(" + sig + ") ([]" + rowType + ", error) {\n")
	b.WriteString("\titems, err := retry.RetryWithResult(ctx, func(ctx context.Context) ([]" + rowType + ", error) {\n")
	if len(params) > 0 {
		b.WriteString("\t\trows, err := q.db.QueryContext(ctx, " + constName + args + ")\n")
	} else {
		b.WriteString("\t\trows, err := q.db.QueryContext(ctx, " + constName + ")\n")
	}
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\treturn nil, err\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\tdefer rows.Close()\n")
	b.WriteString("\t\tvar items []" + rowType + "\n")
	b.WriteString("\t\tfor rows.Next() {\n")
	b.WriteString("\t\t\tvar i " + rowType + "\n")
	b.WriteString("\t\t\tif err := rows.Scan(" + scanTargets(cols) + "); err != nil {\n")
	b.WriteString("\t\t\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t\t}\n")
	b.WriteString("\t\t\titems = append(items, i)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\tif err := rows.Err(); err != nil {\n")
	b.WriteString("\t\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t}\n\n")
	b.WriteString("\t\treturn items, nil\n")
	b.WriteString("\t}, retry.WithLabel(\"" + name + "\"))\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, xerrors.WithStackTrace(err)\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\treturn items, nil\n")
	b.WriteString("}\n")
	return b.String()
}

func genExec(name, constName string, q *pb.Query) string {
	var b bytes.Buffer
	params := q.GetParams()
	sig := "ctx context.Context"
	args := ""
	if len(params) > 0 {
		sig = "ctx context.Context, arg " + name + "Params"
		args = namedArgList(params)
	}
	b.WriteString("func (q *Queries) " + name + "(" + sig + ") error {\n")
	b.WriteString("\terr := retry.Retry(ctx, func(ctx context.Context) error {\n")
	if len(params) > 0 {
		b.WriteString("\t\t_, err := q.db.ExecContext(ctx, " + constName + args + ")\n")
	} else {
		b.WriteString("\t\t_, err := q.db.ExecContext(ctx, " + constName + ")\n")
	}
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\treturn xerrors.WithStackTrace(err)\n")
	b.WriteString("\t\t}\n\n")
	b.WriteString("\t\treturn nil\n")
	b.WriteString("\t}, retry.WithLabel(\"" + name + "\"))\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn xerrors.WithStackTrace(err)\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n")
	return b.String()
}

// namedArgList returns the args for QueryRowContext/QueryContext/ExecContext as sql.Named(..., arg.Field).
// Format: ",\n\t\t\tsql.Named(\"id\", arg.ID),\n\t\t\tsql.Named(\"name\", arg.Name),\n\t\t"
func namedArgList(params []*pb.Parameter) string {
	if len(params) == 0 {
		return ""
	}
	var parts []string
	for _, p := range params {
		col := p.GetColumn()
		if col == nil {
			continue
		}
		paramName := col.GetName()
		field := "arg." + toGoField(paramName)
		parts = append(parts, "sql.Named(\""+paramName+"\", "+field+")")
	}
	if len(parts) == 0 {
		return ""
	}
	// Indent: row/rows/exec is 2 tabs; sql.Named continuation 3 tabs; closing paren 2 tabs.
	return ",\n\t\t\t" + strings.Join(parts, ",\n\t\t\t") + ",\n\t\t"
}

func toGoStruct(s string) string {
	if s == "" {
		return "T"
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func toGoField(s string) string {
	if s == "" {
		return "F"
	}
	switch strings.ToLower(s) {
	case "id":
		return "ID"
	default:
		return strings.ToUpper(s[:1]) + s[1:]
	}
}

func toGoConst(s string) string {
	return strings.ToLower(s[:1]) + s[1:]
}

func scanTargets(cols []*pb.Column) string {
	var parts []string
	for _, c := range cols {
		parts = append(parts, "&i."+toGoField(c.GetName()))
	}
	return strings.Join(parts, ", ")
}
